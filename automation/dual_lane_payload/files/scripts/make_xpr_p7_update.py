"""Write scripts/update_NOC_PQATTEST_xpr.tcl: brings every registered simulation bench into NOC_PQATTEST.xpr.

The dual-lane variants (rtl/dual_lane/) share module names with the production files in sources_1 (NOC_PKG,
pq_measurement, ...), so they can never join sources_1 or sim_1 (CLAUDE.md: a variant and its original never share
a source list). Instead each non-mutant simulation job in scripts/dual_lane_jobs.json gets its own simulation fileset
dl_<job> holding exactly the job's registered source list, the same way scripts/dual_lane_export.tcl builds it
(all sources in one simset, Vivado compile order), plus the job's top, defines, include dirs and TB time limit. Every
dl_ simset points at an empty design set dl_src_<n> (one per define/include combination; XSim takes defines and
include dirs from the design set too), so production sources_1 is never compiled with it. sources_1,
constrs_1, sim_1 and the synthesis/implementation runs are not touched. Re-sourcing replaces all dl_* filesets.

Benches that $readmemh a plain file name (looked up in the XSim run directory first) also get those .mem files from
their include dirs added to the set (Vivado copies them into the run directory), plus the bench's own path-select
define (`ifdef <X>_LOCAL, e.g. S2_LOCAL) so it reads them there instead of the harness snapshot path.

P7 synthesis/implementation: the registered P&R job p7_subsystem_pnr gets its own design set dl_p7_src (its 51
files, top, defines), constraint set dl_p7_constrs (its XDC) and runs synth_p7 / impl_p7 (out_of_context,
-flatten_hierarchy none, S1-PNR-DIR directives as in scripts/d4_crypto_ooc_child.tcl). synth_1/impl_1 and sources_1
stay the production design and remain the active runs. Re-sourcing deletes and recreates synth_p7/impl_p7 (their run
results go with them).

P7 board bitstream (DECISION_REGISTER D5-BOARD): design set dl_p7_board_src (the same 51 files + the board wrapper
synth/p7_board/pq_p7_board_top.sv, top pq_p7_board_top), constraint set dl_p7_board_constrs (Arty A7-100T pins) and runs
synth_p7_board / impl_p7_board (full in-context flow to write_bitstream, S1-PNR-DIR directives), plus the smoke
simulation set dl_p7_board_smoke. Re-sourcing deletes and recreates them as well.

Mutant jobs (source edited at run time by the harness) and the other OOC jobs are not included. Not evidence:
registered results come only from scripts/dual_lane.py.

S4 (2026-11-05, docs/decisions/S4_AREA_CONTRACT.md sec. 6): release benches touching KMAC are replaced by their S4 re-runs;
the P7 design sets hold the S4 list; the old synth_p7* / impl_p7* project runs are deleted and NOT recreated, because project
synthesis cannot reproduce the registered S4-F3 mesh split. The three P7 bitstreams (SoC-profile area, all-exports area,
demo) are built by scripts/p7_bitstream_flow.tcl from scripts/p7_bitstream_sources.tcl (written here). The run paragraphs
above describe the pre-S4 project.

Usage: python scripts/make_xpr_p7_update.py
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JOBS = json.loads((ROOT / 'scripts' / 'dual_lane_jobs.json').read_text())['jobs']

def tcl_list(items):
    return '{' + ' '.join(items) + '}'

# Release (2026-11-03): the project carries the release benches only (registry selection `rel`, non-mutant): every
# P7 check of I-5 .. I-7 on the release source list. Older dl_* sets (superseded lists, 0x8 window) are dropped.
# S4 (2026-11-04, docs/decisions/S4_AREA_CONTRACT.md): every release bench whose list holds a KMAC file is replaced by its S4
# re-run (same bench and counts on the S4 list with the A5 KMAC variants); the other release benches stay as they are.
S4OF = {j['s4_of']: j for j in JOBS if j.get('selection') == 's4' and j.get('s4_of') and not j.get('mutant')}
sims = [S4OF.get(j['id'], j) for j in JOBS if j['kind'] == 'simulation' and not j.get('mutant') and j.get('selection') == 'rel']
sims = [json.loads(json.dumps(j)) for j in sims]
for j in sims:
    for p in j['sources'] + j.get('include_dirs', []):
        if not (ROOT / p).exists(): raise SystemExit(f'{j["id"]}: missing {p}')
lines = [
    '# Generated by scripts/make_xpr_p7_update.py from scripts/dual_lane_jobs.json. Do not edit by hand.',
    '# Open NOC_PQATTEST.xpr in Vivado, then in the Tcl console:  source <this file>',
    f'# Adds {len(sims)} simulation filesets dl_<job> (one per registered non-mutant simulation job).',
    '# Also adds the P7 design sets dl_p7_*_src (S4 list). P7 bitstreams: scripts/build_release_bitstreams.tcl (registered S4 flow).',
    '# Re-sourcing replaces all dl_* filesets and the P7 runs.',
    '# Run one:  dl_sim <job>      (e.g. dl_sim n2p7_rtt)      List:  dl_list      Back to the original: dl_sim_1',
    '# GUI: a dl_ set must be the ACTIVE simset (Sources > right-click dl_<job> > Make Active) before Run Simulation;',
    '#      Vivado applies the defines/include dirs of the active set only. dl_sim does this for you.',
    'set P [current_project -quiet]',
    'if {$P eq ""} { error "Open NOC_PQATTEST.xpr first, then source this file." }',
    'if {[get_property NAME $P] ne "NOC_PQATTEST"} { error "Current project is [get_property NAME $P], not NOC_PQATTEST." }',
    'set ::dl_root [get_property DIRECTORY $P]',
    'current_fileset -simset [get_filesets sim_1]',
    'foreach r {impl_p7_soc synth_p7_soc impl_p7_area synth_p7_area impl_p7_board synth_p7_board impl_p7 synth_p7} { if {[get_runs -quiet $r] ne ""} { reset_run $r; delete_runs [get_runs $r] } }',
    'foreach fs [get_filesets -quiet -filter {FILESET_TYPE == SimulationSrcs} dl_*] { delete_fileset $fs }',
    'foreach fs [get_filesets -quiet dl_*] { delete_fileset $fs }',
    'set ::dl_jobs {}',
    'proc dl_srcset {name defines incs} {',
    '  set ss [create_fileset -srcset $name]',
    '  if {[llength $defines]} { set_property verilog_define $defines $ss }',
    '  if {[llength $incs]} { set_property include_dirs [lmap s $incs {file join $::dl_root $s}] $ss }',
    '}',
    'proc dl_job {id srcset top srcs defines incs runtime checks mems} {',
    '  set fs [create_fileset -simset dl_$id]',
    '  set_property SOURCE_SET $srcset $fs',
    '  add_files -norecurse -fileset $fs [lmap s $srcs {file join $::dl_root $s}]',
    '  set_property top $top $fs',
    '  set_property top_lib xil_defaultlib $fs',
    '  if {[llength $defines]} { set_property verilog_define $defines $fs }',
    '  if {[llength $incs]} { set_property include_dirs [lmap s $incs {file join $::dl_root $s}] $fs }',
    '  set_property -name {xsim.simulate.runtime} -value $runtime -objects $fs',
    '  set_property -name {xsim.simulate.log_all_signals} -value {false} -objects $fs',
    '  if {[llength $mems]} { add_files -norecurse -fileset $fs [lmap s $mems {file join $::dl_root $s}] }',
    '  update_compile_order -fileset $fs',
    '  lappend ::dl_jobs [list $id $top $checks]',
    '}',
    'proc dl_list {} { foreach j $::dl_jobs { puts [format "%-30s top=%-28s expected CHECKS=%s" {*}$j] } }',
    'proc dl_sim {id} { current_fileset -simset [get_filesets dl_$id]; launch_simulation -simset [get_filesets dl_$id] -mode behavioral }',
    'proc dl_sim_1 {} { current_fileset -simset [get_filesets sim_1] }',
]
LOCAL = re.compile(r'`ifdef\s+(\w+_LOCAL)\s*\n\s*\$readmem')
for j in sims:
    local = sorted({d for s in j['sources'] for d in LOCAL.findall((ROOT / s).read_text(errors='ignore'))})
    j['defines'] = list(j.get('defines', [])) + local
srcsets = {}
for j in sims:
    key = (tuple(j.get('defines', [])), tuple(i.rstrip('/') for i in j.get('include_dirs', [])))
    if key not in srcsets:
        srcsets[key] = f'dl_src_{len(srcsets)}'
        lines.append(f'dl_srcset {srcsets[key]} {tcl_list(key[0])} {tcl_list(key[1])}')
for j in sims:
    inc = [i.rstrip('/') for i in j.get('include_dirs', [])]
    key = (tuple(j.get('defines', [])), tuple(inc))
    names = {n for s in j['sources'] for n in re.findall(r'\$readmem[hb]\s*\(\s*"([^"/]+)"', (ROOT / s).read_text(errors='ignore'))}
    mems = sorted(f'{d}/{n}' for d in inc for n in names if (ROOT / d / n).is_file())
    if len(mems) != len(names): raise SystemExit(f'{j["id"]}: run-time files {sorted(names)} not all found in {inc}')
    lines.append(f'dl_job {j["id"]} {srcsets[key]} {j["top"]} {tcl_list(j["sources"])} {tcl_list(j.get("defines", []))} '
                 f'{tcl_list(inc)} {j.get("tb_time_limit", "25ms")} {j.get("checks")} {tcl_list(mems)}')
pnr = next(j for j in JOBS if j['id'] == 's4r_p7_pnr')   # S4 source list (release + A5 KMAC variants), S4-F3 flow
if (pnr.get('synth_flatten'), pnr.get('synth_directive'), pnr.get('synth_mesh_split')) != ('rebuilt', 'AreaOptimized_high', True): raise SystemExit('s4r_p7_pnr flow changed')
BOARD_SRC = ['synth/p7_board/pq_p7_board_top.sv']
BOARD_XDC = 'synth/p7_board/pq_p7_board_arty.xdc'
BOARD_TB = 'synth/p7_board/tb_p7_board_top.sv'
AREA_SRC = ['synth/n13/n13_observe.sv', 'synth/n13/pq_p7_n13_top.sv', 'synth/p7_area/pq_p7_area_top.sv']
AREA_XDC = 'synth/p7_area/pq_p7_area_arty.xdc'
AREA_TB = 'synth/p7_area/tb_p7_area_top.sv'
SOC_SRC = ['synth/p7_soc/pq_p7_soc_core.sv', 'synth/n13/n13_observe.sv', 'synth/p7_area/pq_p7_soc_area_top.sv']
SOC_XDC = 'synth/p7_area/pq_p7_soc_area_arty.xdc'
SOC_TB = 'synth/p7_area/tb_p7_soc_area_top.sv'
for p_ in pnr['sources'] + [pnr['constraints']] + BOARD_SRC + [BOARD_XDC, BOARD_TB] + AREA_SRC + [AREA_XDC, AREA_TB] + SOC_SRC + [SOC_XDC, SOC_TB]:
    if not (ROOT / p_).exists(): raise SystemExit(f'p7_subsystem_pnr: missing {p_}')
lines += [
    '# P7 synthesis + implementation (registered job p7_subsystem_pnr)',
    'create_fileset -srcset dl_p7_src',
    f'add_files -norecurse -fileset dl_p7_src [lmap s {tcl_list(pnr["sources"])} {{file join $::dl_root $s}}]',
    f'set_property top {pnr["top"]} [get_filesets dl_p7_src]',
    f'set_property verilog_define {tcl_list(pnr.get("defines", []))} [get_filesets dl_p7_src]',
    'update_compile_order -fileset dl_p7_src',
    'create_fileset -constrset dl_p7_constrs',
    f'add_files -norecurse -fileset dl_p7_constrs [file join $::dl_root {pnr["constraints"]}]',
    '# P7 board bitstream (DECISION_REGISTER D5-BOARD): same 51 files + board wrapper, Arty A7-100T pins',
    'create_fileset -srcset dl_p7_board_src',
    f'add_files -norecurse -fileset dl_p7_board_src [lmap s [concat {tcl_list(pnr["sources"])} {tcl_list(BOARD_SRC)}] {{file join $::dl_root $s}}]',
    'set_property top pq_p7_board_top [get_filesets dl_p7_board_src]',
    f'set_property verilog_define {tcl_list(pnr.get("defines", []))} [get_filesets dl_p7_board_src]',
    'update_compile_order -fileset dl_p7_board_src',
    'create_fileset -constrset dl_p7_board_constrs',
    f'add_files -norecurse -fileset dl_p7_board_constrs [file join $::dl_root {BOARD_XDC}]',
    'set fs [create_fileset -simset dl_p7_board_smoke]',
    'set_property SOURCE_SET dl_p7_board_src $fs',
    f'add_files -norecurse -fileset $fs [file join $::dl_root {BOARD_TB}]',
    'set_property top tb_p7_board_top $fs',
    'set_property top_lib xil_defaultlib $fs',
    f'set_property verilog_define {tcl_list(pnr.get("defines", []))} $fs',
    'set_property -name {xsim.simulate.runtime} -value {3ms} -objects $fs',
    'set_property -name {xsim.simulate.log_all_signals} -value {false} -objects $fs',
    'update_compile_order -fileset $fs',
    '# Accurate-area bitstream: the N-13 secure top (nothing constant-folds) behind the board MMCM, Arty pins',
    'create_fileset -srcset dl_p7_area_src',
    f'add_files -norecurse -fileset dl_p7_area_src [lmap s [concat {tcl_list(pnr["sources"])} {tcl_list(AREA_SRC)}] {{file join $::dl_root $s}}]',
    'set_property top pq_p7_area_top [get_filesets dl_p7_area_src]',
    f'set_property verilog_define {tcl_list(pnr.get("defines", []))} [get_filesets dl_p7_area_src]',
    'update_compile_order -fileset dl_p7_area_src',
    'create_fileset -constrset dl_p7_area_constrs',
    f'add_files -norecurse -fileset dl_p7_area_constrs [file join $::dl_root {AREA_XDC}]',
    'set fs [create_fileset -simset dl_p7_area_smoke]',
    'set_property SOURCE_SET dl_p7_area_src $fs',
    f'add_files -norecurse -fileset $fs [file join $::dl_root {AREA_TB}]',
    'set_property top tb_p7_area_top $fs',
    'set_property top_lib xil_defaultlib $fs',
    f'set_property verilog_define {tcl_list(pnr.get("defines", []))} $fs',
    'set_property -name {xsim.simulate.runtime} -value {3ms} -objects $fs',
    'set_property -name {xsim.simulate.log_all_signals} -value {false} -objects $fs',
    'update_compile_order -fileset $fs',
    '# SoC-profile accurate-area bitstream (S4-SOC): pq_p7_soc_core (observation-only exports unconnected) behind the board MMCM',
    'create_fileset -srcset dl_p7_soc_src',
    f'add_files -norecurse -fileset dl_p7_soc_src [lmap s [concat {tcl_list(pnr["sources"])} {tcl_list(SOC_SRC)}] {{file join $::dl_root $s}}]',
    'set_property top pq_p7_soc_area_top [get_filesets dl_p7_soc_src]',
    f'set_property verilog_define {tcl_list(pnr.get("defines", []))} [get_filesets dl_p7_soc_src]',
    'update_compile_order -fileset dl_p7_soc_src',
    'create_fileset -constrset dl_p7_soc_constrs',
    f'add_files -norecurse -fileset dl_p7_soc_constrs [file join $::dl_root {SOC_XDC}]',
    'set fs [create_fileset -simset dl_p7_soc_smoke]',
    'set_property SOURCE_SET dl_p7_soc_src $fs',
    f'add_files -norecurse -fileset $fs [file join $::dl_root {SOC_TB}]',
    'set_property top tb_p7_soc_area_top $fs',
    'set_property top_lib xil_defaultlib $fs',
    f'set_property verilog_define {tcl_list(pnr.get("defines", []))} $fs',
    'set_property -name {xsim.simulate.runtime} -value {3ms} -objects $fs',
    'set_property -name {xsim.simulate.log_all_signals} -value {false} -objects $fs',
    'update_compile_order -fileset $fs',
    'current_run -synthesis [get_runs synth_1]',
    'current_run -implementation [get_runs impl_1]',
    'current_fileset -simset [get_filesets sim_1]',
    'puts "NOC_PQATTEST: added [llength $::dl_jobs] dl_* simulation filesets; sim_1 is still the active simset."',
    'puts "NOC_PQATTEST: P7 design sets dl_p7_src / dl_p7_board_src / dl_p7_area_src / dl_p7_soc_src hold the S4 list (browse / simulate)."',
    'puts "NOC_PQATTEST: P7 bitstreams are built by the registered S4 flow (mesh split + rebuilt + AreaOptimized_high): source scripts/build_release_bitstreams.tcl"',
    'puts "Run one with: dl_sim <job>   (list them with: dl_list)"',
]
# Expected results / sources for scripts/run_release_all.tcl (verification inside the project; frozen counts from the registry)
BS = chr(92)   # Tcl line continuation
exp = ['# Generated by scripts/make_xpr_p7_update.py from scripts/dual_lane_jobs.json. Do not edit by hand.',
       'set ::rel_expected [dict create ' + BS]
exp += [f'  dl_{j["id"]} {j["checks"]} ' + BS for j in sims]
exp += ['  dl_p7_board_smoke 6 ' + BS, '  dl_p7_area_smoke 3 ' + BS, '  dl_p7_soc_smoke 3]',
        'set ::rel_sources [dict create ' + BS,
        f'  dl_p7_src {tcl_list(pnr["sources"])} ' + BS,
        f'  dl_p7_board_src {tcl_list(pnr["sources"] + BOARD_SRC)} ' + BS,
        f'  dl_p7_area_src {tcl_list(pnr["sources"] + AREA_SRC)} ' + BS,
        f'  dl_p7_soc_src {tcl_list(pnr["sources"] + SOC_SRC)}]']
# Expected-FAIL TB controls (registry tb_control; same rule as dual_lane_verify.judge_control) and required lines
def tl(pats): return '[list ' + ' '.join('{' + p + '}' for p in pats) + ']'
exp += ['set ::rel_controls [dict create]', 'set ::rel_required [dict create]']
for j in sims:
    c = j.get('tb_control')
    if c:
        exp.append(f'dict set ::rel_controls dl_{j["id"]} [dict create errors {c["errors"]} oracle {tl(c["oracle"])} '
                   f'allowed {tl(c["allowed_fail"])} forbid {tl(c.get("forbid", []))}]')
    if j.get('required_lines'):
        exp.append(f'dict set ::rel_required dl_{j["id"]} [list ' + ' '.join('[list {' + p + '} ' + str(n) + ']' for p, n in j['required_lines']) + ']')
# P7 bitstreams (S4_AREA_CONTRACT.md sec. 6): built by scripts/p7_bitstream_flow.tcl with the registered S4 flow, not by project runs
BITS = [('p7_soc', 'pq_p7_soc_area_top', SOC_SRC, SOC_XDC), ('p7_area', 'pq_p7_area_top', AREA_SRC, AREA_XDC),
        ('p7_board', 'pq_p7_board_top', BOARD_SRC, BOARD_XDC)]
bl = ['# Generated by scripts/make_xpr_p7_update.py from scripts/dual_lane_jobs.json (s4r_p7_pnr list). Do not edit by hand.',
      'set ::p7_bit [dict create]']
for n_, top_, extra_, xdc_ in BITS:
    bl.append(f'dict set ::p7_bit {n_} [dict create top {top_} xdc {xdc_} defines {tcl_list(pnr.get("defines", []))} sources {tcl_list(pnr["sources"] + extra_)}]')
(ROOT / 'scripts' / 'p7_bitstream_sources.tcl').write_text(chr(10).join(bl) + chr(10), encoding='utf-8')
(ROOT / 'scripts' / 'release_expected.tcl').write_text(chr(10).join(exp) + chr(10), encoding='utf-8')
out = ROOT / 'scripts' / 'update_NOC_PQATTEST_xpr.tcl'
out.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(out, len(sims), 'jobs')
