"""Merged-SoC source list (NOT evidence): writes scripts/merged_bitstream_sources.tcl for scripts/merged_bitstream_flow.tcl
and scripts/merged_project_update.tcl.

List = the released p7_board list (scripts/p7_bitstream_sources.tcl, S4 flow) with the I-9 same-module variants swapped in
(scripts/prepare_i9.I9MAP: never variant + original together), minus the P7 board top, plus the merged core, the CPU-tile
module and the merged board top.

FILL IN when the RISC-V package arrives (only this block):
  RISCV_SOURCES   the RISC-V lane's files (cpu_tile_noc and everything below it), repository-relative, compile order
  CPU_TILE_MODULE 'cpu_tile_noc' (the stub until then)
  EXTRA_DEFINES   any defines the RISC-V files need
  MEM_INIT_FILES  firmware images ($readmemh) the CPU tiles load, repository-relative (copied next to the run)
Then: python scripts/make_merged_sources.py  (prints the list and the preflight result).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from prepare_i9 import I9MAP   # noqa: E402

# ------------------------------------------------------------------ FILL IN (RISC-V package)
# Filled 2026-11-07 (R-4, Lane 1): the real CPU tile (I-13 / I-14 benches; B7 scratch synthesis 2,938 LUT per tile).
RISCV_SOURCES = ['rtl/riscv/' + f for f in ['picorv32.v', 'picorv32_adapter.sv', 'addr_decode.sv', 'uart_tx.sv', 'uart_mmio.sv',
                 'gpio.sv', 'tile_status.sv', 'tile_top.sv', 'mem_bram.sv', 'tile_mem_wrapper.sv', 'tmem_app_bridge.sv',
                 'meas_window_reader.sv', 'meas_imem_hasher.sv', 'cpu_tile_noc.sv']]
CPU_TILE_MODULE = 'cpu_tile_noc'
EXTRA_DEFINES = ['REAL_CPU_TILE']        # board top: demo_fw provisioning + LED map
MEM_INIT_FILES = ['sw/riscv/demo_fw_v3.hex']
# ------------------------------------------------------------------

MERGED = ['rtl/dual_lane/merged/pq_soc_merged_core.sv', 'synth/merged/pq_merged_board_top.sv']
STUB = 'rtl/dual_lane/merged/cpu_tile_noc_stub.sv'


def board_list():
    t = (ROOT / 'scripts/p7_bitstream_sources.tcl').read_text(encoding='utf-8')
    m = re.search(r'dict set ::p7_bit p7_board \[dict create .*? sources \{([^}]*)\}\]', t)
    if not m:
        raise SystemExit('p7_board entry not found in scripts/p7_bitstream_sources.tcl')
    return m.group(1).split()


def build():
    srcs = [I9MAP.get(s, s) for s in board_list() if s != 'synth/p7_board/pq_p7_board_top.sv']
    cpu = RISCV_SOURCES if CPU_TILE_MODULE != 'cpu_tile_noc_stub' else [STUB]
    core, top = MERGED
    srcs = srcs + cpu + [core, top]
    # preflight: every file exists; no variant together with its original; no duplicate module definitions
    missing = [s for s in srcs + MEM_INIT_FILES if not (ROOT / s).is_file()]
    both = [(o, v) for o, v in I9MAP.items() if o in srcs and v in srcs]
    mods = {}
    for s in srcs:
        for name in re.findall(r'^\s*module\s+(\w+)', (ROOT / s).read_text(encoding='utf-8', errors='replace'), re.M):
            mods.setdefault(name, []).append(s)
    dup = {k: v for k, v in mods.items() if len(v) > 1}
    if missing or both or dup:
        raise SystemExit(f'PREFLIGHT FAIL missing={missing} variant+original={both} duplicate_modules={dup}')
    defines = ['PQ_MAC_ON', f'CPU_TILE_MODULE={CPU_TILE_MODULE}'] + EXTRA_DEFINES
    return srcs, defines


def write_titan_list(lines):
    from prepare_titan import variant_map

    mapping = variant_map()
    srcs, defines = build()
    if not set(mapping) <= set(srcs):
        raise ValueError("Missing I-9 inputs for TITAN board list")
    titan = [mapping.get(path, path) for path in srcs]
    if any(not (ROOT / path).is_file() for path in titan):
        raise ValueError("TITAN board list contains missing sources; run prepare_titan.py")
    entry = lines[2].replace(f'sources {{{" ".join(srcs)}}}', f'sources {{{" ".join(titan)}}}')
    content = "\n".join([lines[0], lines[1], entry, ""])
    (ROOT / 'scripts/merged_bitstream_sources_titan.tcl').write_text(content, encoding='utf-8', newline='\n')


def main():
    srcs, defines = build()
    lines = ['# Generated by scripts/make_merged_sources.py. Do not edit by hand (edit the FILL IN block there).',
             'set ::merged_bit [dict create]',
             'dict set ::merged_bit merged_board [dict create top pq_merged_board_top xdc synth/merged/pq_merged_board_arty.xdc '
             f'defines {{{" ".join(defines)}}} mem_init {{{" ".join(MEM_INIT_FILES)}}} sources {{{" ".join(srcs)}}}]', '']
    (ROOT / 'scripts/merged_bitstream_sources.tcl').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    if '--titan' in sys.argv[1:]:
        write_titan_list(lines)
    print(f'MERGED_SOURCES: PASS ({len(srcs)} files; CPU tile = {CPU_TILE_MODULE}; defines {defines})')
    for s in srcs:
        print('  ' + s)
    return 0


if __name__ == '__main__':
    sys.exit(main())
