"""D-SYN-1: generate synthesizable crypto variants in rtl/dual_lane/ from the hash-checked protected originals, plus
TB-only renamed copies of the originals for the equivalence benches. The protected files are only read."""
import hashlib, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
S = ROOT / 'NOC_PQATTEST.srcs/sources_1/new'; D = ROOT / 'rtl/dual_lane'; E = ROOT / 'sim/dual_lane/dsyn1'
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
base = json.loads((ROOT / 'automation/dual_lane_payload/baseline_before.json').read_text())['files']

def original(name):
    p = S / name; rel = 'NOC_PQATTEST.srcs/sources_1/new/' + name
    if sha(p) != base[rel]: raise SystemExit(f'protected original changed: {rel}')
    return p.read_text(encoding='utf-8'), p

def replace_once(t, a, b):
    if t.count(a) != 1: raise SystemExit('anchor not unique: ' + a[:60])
    return t.replace(a, b)

def main():
    D.mkdir(parents=True, exist_ok=True); E.mkdir(parents=True, exist_ok=True)
    out = {}
    # 1. keccak_iota: guard the simulation-only assertion block. No other change.
    t, p = original('pq_keccak_iota.sv')
    a = '    always_comb begin\n        a_round_in_range:'
    t = replace_once(t, a, '`ifndef SYNTHESIS\n' + a)
    a2 = '                round, NUM_ROUNDS\n            );\n    end\n'
    t = replace_once(t, a2, a2 + '`endif\n')
    (D / 'pq_keccak_iota.sv').write_text(t, encoding='utf-8', newline='\n'); out['pq_keccak_iota.sv'] = p
    # 2. sha3_pad: constant-bound loop; domain byte and final bit unchanged.
    t, p = original('SHA3_PAD.sv')
    a = ('                for (int i = valid_bytes; i < RATE_BYTES; i++) begin\n'
         '                    padded_block[i*8 +: 8] = 8\'h00;\n'
         '                end\n')
    b = ('                for (int i = 0; i < RATE_BYTES; i++) begin\n'
         '                    if (i >= valid_bytes) padded_block[i*8 +: 8] = 8\'h00;\n'
         '                end\n')
    t = replace_once(t, a, b)
    (D / 'SHA3_PAD.sv').write_text(t, encoding='utf-8', newline='\n'); out['SHA3_PAD.sv'] = p
    # TB-only renamed copies of the originals (equivalence benches only; never in a synthesis list).
    for name, mod, ren in [('SHA3_PAD.sv', 'sha3_pad', 'sha3_pad_orig_dsyn1'), ('pq_keccak_iota.sv', 'keccak_iota', 'keccak_iota_orig_dsyn1')]:
        t, _ = original(name)
        t = replace_once(t, f'module {mod}\n', f'module {ren}\n')
        (E / f'{ren}.sv').write_text('// GENERATED by scripts/prepare_dsyn1_variants.py from the protected original; TB-only.\n' + t, encoding='utf-8', newline='\n')
    prov = json.loads((D / 'variant_provenance.json').read_text())
    for name, p in out.items():
        prov[name] = dict(base=sha(p), variant=sha(D / name), decision='docs/decisions/D-SYN-1-crypto-synth-fixes.md')
    (D / 'variant_provenance.json').write_text(json.dumps(prov, indent=2) + '\n', encoding='utf-8', newline='\n')
    print('DSYN1_VARIANTS: written', sorted(out))

if __name__ == '__main__': main()
