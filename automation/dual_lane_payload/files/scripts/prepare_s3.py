"""S3 (DECISION_REGISTER S3-T1, S3-A1; docs/decisions/S3_T1_A1_CONTRACT.md). Generates, by exact-anchor edits that must
match once, from pinned sources (hashes in rtl/dual_lane/s3_provenance.json):
  rtl/dual_lane/pq_keccak_f1600.sv        T1: keccak_f1600 with the next-state select replicated per 64-bit lane
  rtl/dual_lane/kmac_128_xp.sv            A1: kmac128_xp, permutation port (p_*) (A5 withdrawn after measurement, contract sec. 6)
  rtl/dual_lane/SHA3_256_xp.sv            A1+A6: sha3_256_xp, permutation port, single pre-padded block (protected original read only)
  rtl/dual_lane/pq_kmac_share_xp.sv       A1: pq_kmac_share on kmac128_xp, port passed through
  rtl/dual_lane/pq_measurement_xp.sv      A1+A6: pq_measurement (D-SYN-2 variant) on sha3_256_xp; the builder writes the SHA3 padding
  NOC_PQATTEST.srcs/sim_1/new/tb_s3_meas_equiv.sv  A6 exhaustive equivalence bench (copy of tb_dsyn2_measurement_equiv)
  rtl/dual_lane/pq_attest_protocol_s3.sv  A1: controller with ONE keccak_f1600 shared by the KMAC and the measurement
Usage: python scripts/prepare_s3.py            (writes the variants and the provenance file)
       python scripts/check_s3.py              (regenerates in memory and compares; registered job s3_variant)"""
import hashlib, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
S = 'NOC_PQATTEST.srcs/sources_1/new/'; D = 'rtl/dual_lane/'
CONTRACT = 'docs/decisions/S3_T1_A1_CONTRACT.md'
sha = lambda b: hashlib.sha256(b).hexdigest()

def edit(text, reps, what):
    for a, b in reps:
        if text.count(a) != 1: raise SystemExit(f'{what}: anchor not unique/found: {a[:80]!r}')
        text = text.replace(a, b)
    return text

def cut(text, head, what):
    """Remove the instance starting at `head` up to its closing '\n    );\n'; return (before, after)."""
    if text.count(head) != 1: raise SystemExit(f'{what}: instance anchor not unique/found: {head!r}')
    i = text.index(head); j = text.index('\n    );\n', i) + len('\n    );\n')
    return text[:i], text[j:]

def hdr(src, tag):
    return f'// GENERATED by scripts/prepare_s3.py from {src} ({tag}, {CONTRACT}). Do not edit.\n'

PORT_DECL = ('    // S3-A1: external permutation port; the internal keccak_f1600 is removed and shared by the caller.\n'
             '    output logic               p_start,\n'
             '    output keccak_pkg::state_t p_state_in,\n'
             '    input  keccak_pkg::state_t p_state_out,\n'
             '    input  logic               p_busy,\n'
             '    input  logic               p_done\n);')
PORT_CONN = ('        .p_start     (p_start),\n        .p_state_in  (p_state_in),\n        .p_state_out (p_state_out),\n'
             '        .p_busy      (p_busy),\n        .p_done      (p_done)\n    );')

def keccak(t):
    t = edit(t, [
        ('    keccak_state_e fsm_state;\n',
         '    keccak_state_e fsm_state;\n'
         '    keccak_state_e fsm_next;\n\n'
         '    // S3-T1: one registered copy of fsm_state per 64-bit lane, so each copy drives 64 state bits instead of\n'
         '    // one bit driving all 1,600 (registered P7: fanout 1,618, 97 % route on the critical path). Every copy takes\n'
         '    // fsm_next in the same cycle as fsm_state, so the behaviour is cycle-identical (T1-I1, T1-I2).\n'
         '    (* keep = "true", fsm_encoding = "none" *) keccak_state_e fsm_rep [STATE_DIM][STATE_DIM];\n'),
        ("            state_reg   <= '{default:'0};\n            round_reg   <= '0;\n            fsm_state   <= KECCAK_IDLE;",
         "            round_reg   <= '0;\n            fsm_state   <= KECCAK_IDLE;"),
        ('                        state_reg <= state_in;\n', ''),
        ("                    state_reg   <= round_out;\n\n                    round_valid <= 1'b1;",
         "                    round_valid <= 1'b1;"),
        ("                    state_reg <= '{default:'0};\n                    round_reg <= '0;\n                    fsm_state <= KECCAK_IDLE;",
         "                    round_reg <= '0;\n                    fsm_state <= KECCAK_IDLE;"),
        ('    //-------------------------------------------------------------------------\n    // Outputs\n',
         '    //-------------------------------------------------------------------------\n'
         '    // S3-T1: state register, one lane per replicated select. Same branches as the original FSM:\n'
         '    // reset -> 0, IDLE & start -> state_in, RUN -> round_out, DONE -> hold, invalid -> 0.\n'
         '    //-------------------------------------------------------------------------\n\n'
         '    always_comb begin\n'
         '        fsm_next = fsm_state;\n'
         '        case (fsm_state)\n'
         '            KECCAK_IDLE: if (start) fsm_next = KECCAK_RUN;\n'
         '            KECCAK_RUN:  if (round_reg == round_t\'(NUM_ROUNDS - 1)) fsm_next = KECCAK_DONE;\n'
         '            KECCAK_DONE: fsm_next = KECCAK_IDLE;\n'
         '            default:     fsm_next = KECCAK_IDLE;\n'
         '        endcase\n'
         '    end\n\n'
         '    always_ff @(posedge clk) begin\n'
         '        for (int x = 0; x < STATE_DIM; x++) begin\n'
         '            for (int y = 0; y < STATE_DIM; y++) begin\n'
         '                if (rst) begin\n'
         "                    state_reg[x][y] <= '0;\n"
         '                    fsm_rep[x][y]   <= KECCAK_IDLE;\n'
         '                end\n'
         '                else begin\n'
         '                    fsm_rep[x][y] <= fsm_next;\n'
         '                    case (fsm_rep[x][y])\n'
         '                        KECCAK_IDLE: if (start) state_reg[x][y] <= state_in[x][y];\n'
         '                        KECCAK_RUN:  state_reg[x][y] <= round_out[x][y];\n'
         '                        KECCAK_DONE: ;\n'
         "                        default:     state_reg[x][y] <= '0;\n"
         '                    endcase\n'
         '                end\n'
         '            end\n'
         '        end\n'
         '    end\n\n'
         '    // T1-I2: every lane copy equals fsm_state after reset.\n'
         '    // synthesis translate_off\n'
         '    always_ff @(posedge clk) begin\n'
         '        if (!rst)\n'
         '            for (int x = 0; x < STATE_DIM; x++)\n'
         '                for (int y = 0; y < STATE_DIM; y++)\n'
         '                    if (fsm_rep[x][y] !== fsm_state) $error("keccak_f1600: lane select copy [%0d][%0d] differs from fsm_state", x, y);\n'
         '    end\n'
         '    // synthesis translate_on\n\n'
         '    //-------------------------------------------------------------------------\n    // Outputs\n'),
        ], 'keccak')
    if 'state_reg <=' in t.replace('state_reg[x][y] <=', ''): raise SystemExit('keccak: an unreplicated state_reg write remains')
    return t

def kmac_xp(t):
    # S3-A5 (no wrapper state copy) was WITHDRAWN after measurement: +790 LUT per engine (contract sec. 6).
    t = edit(t, [('module kmac128\n', 'module kmac128_xp\n'),
                 ('    output logic [TAG_BITS-1:0] tag_out,\n    output logic                busy,\n    output logic                done\n);',
                  '    output logic [TAG_BITS-1:0] tag_out,\n    output logic                busy,\n    output logic                done,\n\n' + PORT_DECL)], 'kmac_xp')
    a, b = cut(t, '    keccak_f1600 u_keccak (', 'kmac_xp')
    return (a + "    // S3-A1: the permutation runs in the caller's shared keccak_f1600 (same start / state / done contract).\n"
            '    assign p_start          = keccak_start;\n    assign p_state_in       = keccak_state_in;\n'
            '    assign keccak_state_out = p_state_out;\n    assign keccak_busy      = p_busy;\n    assign keccak_done      = p_done;\n' + b)

def sha3_1b(t):
    """S3-A1 permutation port + S3-A6 single block: no pad, no absorb, no state copy. The caller (pq_measurement_xp)
    supplies the already padded block; lane i <- block[64i +: 64] at [i%5][i/5] (sha3_absorb mapping from zero)."""
    t = edit(t, [('module sha3_256\n', 'module sha3_256_xp\n'),
                 ('    output logic                             busy,\n    output logic                             done\n);',
                  '    output logic                             busy,\n    output logic                             done,\n\n' + PORT_DECL),
                 ('                        state_reg <= padded_state;\n', ''),
                 ('                        state_reg <= permuted_state;\n', '')], 'sha3_1b')
    for head in ('    sha3_pad u_sha3_pad (', '    sha3_absorb u_sha3_absorb ('):
        a, b = cut(t, head, 'sha3_1b'); t = a + b
    a, b = cut(t, '    keccak_f1600 u_keccak_f1600 (', 'sha3_1b')
    t = (a + '    // S3-A6: one block from the zero state (pq_measurement: max 135 bytes < rate 136); the block arrives padded.\n'
         '    always_comb begin\n'
         "        for (int x = 0; x < STATE_DIM; x++) for (int y = 0; y < STATE_DIM; y++) p_state_in[x][y] = '0;\n"
         '        for (int i = 0; i < RATE_LANES; i++) p_state_in[i % STATE_DIM][i / STATE_DIM] = msg_block_in[i*LANE_WIDTH +: LANE_WIDTH];\n'
         '    end\n'
         '    assign p_start        = keccak_start;\n'
         '    assign permuted_state = p_state_out;\n    assign keccak_busy    = p_busy;\n    assign keccak_done    = p_done;\n'
         '    // synthesis translate_off\n'
         '    always_ff @(posedge clk) if (rst_n && start && ctrl_state == SHA3_CTRL_IDLE && !is_final)\n'
         '        $error("sha3_256_xp: S3-A6 single-block engine started without is_final");\n'
         '    // synthesis translate_on\n' + b)
    rd = [l for l in (x.split('//')[0] for x in t.split('\n')) if 'padded_state' in l and 'state_t padded_state' not in l]
    if rd: raise SystemExit('sha3_1b: padded_state still used: ' + rd[0].strip())
    return t

def kshare_xp(t):
    return edit(t, [('module pq_kmac_share\n', 'module pq_kmac_share_xp\n'),
                    ('    output logic         busy,\n    output logic         done\n);',
                     '    output logic         busy,\n    output logic         done,\n\n' + PORT_DECL),
                    ('    kmac128 #(\n', '    kmac128_xp #(\n'),
                    ('        .done        (done)\n    );', '        .done        (done),\n' + PORT_CONN)], 'kshare_xp')

def meas_xp(t):
    return edit(t, [('module pq_measurement\n', 'module pq_measurement_xp\n'),
                    ('    output logic                         busy,\n    output logic                         done\n);',
                     '    output logic                         busy,\n    output logic                         done,\n\n' + PORT_DECL),
                    ('    sha3_256 u_sha3 (\n', '    sha3_256_xp u_sha3 (\n'),
                    ('        .done         (sha3_done)\n    );', '        .done         (sha3_done),\n' + PORT_CONN),
                    ("                        msg_block_q        <= '0;           // bytes >= req_len stay zero, as in the original",
                     "                        msg_block_q        <= {1'b1, {(RATE_BITS-1){1'b0}}};   // S3-A6: SHA3 end bit preset; bytes >= req_len stay zero"),
                    ('                    if (build_idx_q == sha3_valid_bytes_q) begin\n                        state_q <= S_SHA3;\n',
                     '                    if (build_idx_q == sha3_valid_bytes_q) begin\n'
                     '                        // S3-A6: SHA3 domain byte at offset req_len; it shares byte 135 with the end bit (0x86).\n'
                     '                        for (int b = 0; b < RATE_BYTES; b++)\n'
                     "                            if (build_idx_q == LEN_W'(b)) msg_block_q[b*8 +: 8] <= (b == RATE_BYTES-1) ? 8'h86 : 8'h06;\n"
                     '                        state_q <= S_SHA3;\n')], 'meas_xp')

def tb_meas_equiv(t):
    return edit(t, [('module tb_dsyn2_measurement_equiv;', 'module tb_s3_meas_equiv;'),
        ('`timescale 1ns/1ps\n', '`timescale 1ns/1ps\n// S3-A6 copy of tb_dsyn2_measurement_equiv: the variant is pq_measurement_xp (single-block SHA3, builder pads) on\n'
         '// its own keccak_f1600; the reference and every check and count are unchanged.\n'),
        ('  pq_measurement            u_var (.clk, .rst_n, .start, .tile_id(tile), .config_data(cfg), .config_len(cl),\n'
         '                                   .imem(im), .imem_len(il), .measurement(m_var), .busy(b_var), .done(d_var));',
         '  logic vp_start, vp_busy, vp_done;\n  keccak_pkg::state_t vp_in, vp_out;\n'
         '  pq_measurement_xp         u_var (.clk, .rst_n, .start, .tile_id(tile), .config_data(cfg), .config_len(cl),\n'
         '                                   .imem(im), .imem_len(il), .measurement(m_var), .busy(b_var), .done(d_var),\n'
         '                                   .p_start(vp_start), .p_state_in(vp_in), .p_state_out(vp_out), .p_busy(vp_busy), .p_done(vp_done));\n'
         '  keccak_f1600 u_vcore (.clk, .rst(~rst_n), .start(vp_start), .state_in(vp_in), .state_out(vp_out), .busy(vp_busy),\n'
         '                        .done(vp_done), .round_valid(), .round_index());')], 'tb_meas_equiv')

SHARED = '''    //=========================================================================
    // S3-A1 (DECISION_REGISTER S3-A1, docs/decisions/S3_T1_A1_CONTRACT.md sec. 2): ONE keccak_f1600 shared by the
    // KDF/tag kmac128 (owner KMAC) and the measurement sha3_256 (owner MEAS). The FSM below runs KDF, measurement and
    // tag strictly in sequence, so the two never compete (R5, checked below and by tb_s3_perm_share).
    //   R1 start = kp_start | mp_start; state_in = the starting side's state (sampled only in the start cycle)
    //   R2 owner_meas_q set on a start while the core is idle, held otherwise
    //   R3 done goes to the owner only; both wrappers capture state_out only on their own done
    //   R4 busy is broadcast
    //=========================================================================
    logic               kp_start, mp_start, kp_done, mp_done, sp_busy, sp_done, sp_idle, owner_meas_q;
    keccak_pkg::state_t kp_state_in, mp_state_in, sp_state_in, sp_state_out;
    always_comb sp_state_in = mp_start ? mp_state_in : kp_state_in;
    keccak_f1600 u_perm (
        .clk         (clk),
        .rst         (~rst_n),
        .start       (kp_start | mp_start),
        .state_in    (sp_state_in),
        .state_out   (sp_state_out),
        .busy        (sp_busy),
        .done        (sp_done),
        .round_valid (),
        .round_index ()
    );
    assign sp_idle = !sp_busy && !sp_done;
    always_ff @(posedge clk) begin
        if (!rst_n)                             owner_meas_q <= 1'b0;
        else if (sp_idle && (kp_start | mp_start)) owner_meas_q <= mp_start;
    end
    assign kp_done = sp_done && !owner_meas_q;
    assign mp_done = sp_done &&  owner_meas_q;
    // synthesis translate_off
    always_ff @(posedge clk) begin
        if (rst_n && kp_start && mp_start)
            $error("pq_attestation_controller: KMAC and measurement started the shared keccak_f1600 in the same cycle");
        if (rst_n && (kp_start || mp_start) && !sp_idle)
            $error("pq_attestation_controller: shared keccak_f1600 started while busy");
    end
    // synthesis translate_on

'''

def protocol_s3(t):
    return edit(t, [
        ('    //=========================================================================\n    // D (M-F1 rev 7 R7.8.2): ONE kmac128 shared',
         SHARED + '    //=========================================================================\n    // D (M-F1 rev 7 R7.8.2): ONE kmac128 shared'),
        ('    pq_kmac_share u_pq_kmac_share (\n', '    pq_kmac_share_xp u_pq_kmac_share (\n'),
        ('        .tag_out(ks_tag), .busy(ks_busy), .done(ks_done));',
         '        .tag_out(ks_tag), .busy(ks_busy), .done(ks_done),\n'
         '        .p_start(kp_start), .p_state_in(kp_state_in), .p_state_out(sp_state_out), .p_busy(sp_busy), .p_done(kp_done));'),
        ('    pq_measurement u_pq_measurement (\n', '    pq_measurement_xp u_pq_measurement (\n'),
        ('        .done         (measurement_done)\n    );',
         '        .done         (measurement_done),\n'
         '        .p_start      (mp_start),\n        .p_state_in   (mp_state_in),\n        .p_state_out  (sp_state_out),\n'
         '        .p_busy       (sp_busy),\n        .p_done       (mp_done)\n    );')], 'protocol_s3')

PLAN = [  # (output, source, transform, tag)
    (D + 'pq_keccak_f1600.sv',       S + 'pq_keccak_f1600.sv',     keccak,      'S3-T1'),
    (D + 'kmac_128_xp.sv',           S + 'kmac_128.sv',            kmac_xp,     'S3-A1'),
    (D + 'SHA3_256_xp.sv',           S + 'SHA3_256.sv',            sha3_1b,     'S3-A1/A6'),
    (D + 'pq_kmac_share_xp.sv',      D + 'pq_kmac_share.sv',       kshare_xp,   'S3-A1'),
    (D + 'pq_measurement_xp.sv',     D + 'pq_measurement.sv',      meas_xp,     'S3-A1/A6'),
    (D + 'pq_attest_protocol_s3.sv', D + 'pq_attest_protocol.sv',  protocol_s3, 'S3-A1'),
    ('NOC_PQATTEST.srcs/sim_1/new/tb_s3_meas_equiv.sv', 'NOC_PQATTEST.srcs/sim_1/new/tb_dsyn2_measurement_equiv.sv', tb_meas_equiv, 'S3-A6')]

def build():
    out = {}; prov = {}
    for dst, src, fn, tag in PLAN:
        raw = (ROOT / src).read_bytes(); text = raw.decode('utf-8').replace('\r\n', '\n')
        body = text.split('\n', 1)[1] if text.startswith('// GENERATED by') else text   # keep one GENERATED header
        out[dst] = hdr(src, tag) + fn(body)
        prov[dst] = dict(source=src, source_sha256=sha(raw), output_sha256=sha(out[dst].encode('utf-8')))
    return out, prov

def main():
    out, prov = build()
    for dst, text in out.items(): (ROOT / dst).write_bytes(text.encode('utf-8'))
    (ROOT / D / 's3_provenance.json').write_text(json.dumps(dict(schema=1, contract=CONTRACT, files=prov), indent=2) + '\n', encoding='utf-8')
    for dst in out: print('wrote', dst)

if __name__ == '__main__': main()
