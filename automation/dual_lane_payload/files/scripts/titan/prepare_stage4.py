"""Generate the S4 subsystem from pinned I-9, retaining the S0 variant unchanged."""
from argparse import ArgumentParser
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from prepare_titan import ROOT, build, replace_once

SOURCE = "rtl/dual_lane/pq_noc_subsystem_p7_t1.sv"
SUBSYSTEM = "rtl/dual_lane/titan/s4/pq_noc_subsystem_p7_t1.sv"
TRACKER = "rtl/dual_lane/titan/titan_epoch_tracker.sv"
CHECKS = [
    ("S4.mode", " parameter bit BYPASS_MAC=0,BYPASS_SEQUENCE=0,BYPASS_EPOCH=0,",
     " parameter int TITAN_MODE=0, EPOCH_W=6,\n parameter bit BYPASS_MAC=0,BYPASS_SEQUENCE=0,BYPASS_EPOCH=0,"),
    ("S4.epoch_state", " logic [5:0] sbusy,rbusy;",
     """ logic [5:0] sbusy,rbusy;
 logic [5:0][EPOCH_W-1:0] tile_epoch;
 logic [5:0] tile_epoch_wrap;
 if (EPOCH_W < 1 || EPOCH_W > 6) begin : bad_epoch_width
   initial $fatal(1, "TITAN EPOCH_W must be in 1..6");
 end"""),
    ("S4.epoch_inst", "   assign g_reason[g]=freason;",
     """   if (TITAN_MODE == 4 || TITAN_MODE == 5) begin : EPOCH
     logic auth_update, auth_grant;
     titan_epoch_gate_event #(.ATTESTABLE(g==3 || g==4),
       .BYPASS_ISSUER(BYPASS_ISSUER), .BYPASS_REVOKE(BYPASS_REVOKE)) epoch_event(
       .authenticated_head(rhv[g] || tbi_gv[g]),
       .source(tbi_gv[g] ? tbi_gsrc[g] : rxsrc[g]),
       .message_type(tbi_gv[g] ? tbi_gmsg[g] : rxmsg[g]),
       .control(tbi_gv[g] ? tbi_gctl[g] : rxctl[g]),
       .auth_update_v(auth_update), .auth_is_grant(auth_grant));
     titan_epoch_tracker #(.EPOCH_W(EPOCH_W)) tracker(
       .clk, .rst(rst_i), .auth_update_v(auth_update), .auth_is_grant(auth_grant),
       .epoch_o(tile_epoch[g]), .epoch_wrap_o(tile_epoch_wrap[g]));
   end else begin : NO_EPOCH
     assign tile_epoch[g] = '0;
     assign tile_epoch_wrap[g] = 1'b0;
   end
   assign g_reason[g]=freason;"""),
]
MUTANTS = {
    "bad_grant": ("control[10:7] == 4'd1", "control[10:7] != 4'd0"),
    "drop_revoke": ("auth_is_grant || accepted_revoke", "auth_is_grant"),
    "early_wrap": ("auth_update_v && (&epoch_o)", "auth_update_v && epoch_o == EPOCH_W'((2**EPOCH_W)-2)"),
}


def generated():
    body = build()[SOURCE].decode()
    for name, anchor, replacement in CHECKS:
        body = replace_once(body, anchor, replacement, name)
    prefix = "// TITAN S4 generated by scripts/titan/prepare_stage4.py. DO NOT EDIT.\n"
    result = {SUBSYSTEM: (prefix + body).encode()}
    raw = (ROOT / TRACKER).read_text(encoding="utf-8")
    for name, (anchor, replacement) in MUTANTS.items():
        mutant = replace_once(raw, anchor, replacement, name)
        result[f"rtl/dual_lane/titan/s4/titan_epoch_mut_{name}.sv"] = (prefix + mutant).encode()
    return result


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, raw in generated().items():
        path = ROOT / name
        if args.check:
            if path.read_bytes() != raw:
                raise ValueError(f"TITAN S4 generated content drift: {name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
    print("TITAN_S4_GENERATOR: PASS subsystem=1 checker_variants=3")


if __name__ == "__main__":
    main()
