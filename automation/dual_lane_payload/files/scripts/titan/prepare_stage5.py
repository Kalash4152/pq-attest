"""Generate the S5 subsystem and the three isolated stamp mutations."""
from argparse import ArgumentParser
from pathlib import Path
import json

from prepare_stage4 import ROOT, SUBSYSTEM as S4, replace_once

STAMP = "rtl/dual_lane/titan/titan_epoch_stamp.sv"
SUBSYSTEM = "rtl/dual_lane/titan/s5/pq_noc_subsystem_p7_t1.sv"
CATALOG = "mutants/s5_mutants.json"
ANCHOR = "   assign ctl[g]   =sel_v ? vrtctl : sel_m ? mctl : sel_ep ? ertctl_x : app_control[g];"
WIRING = """   logic [10:0] app_head_control;
   if (TITAN_MODE == 4 || TITAN_MODE == 5) begin : STAMP
     titan_epoch_stamp #(.EPOCH_W(EPOCH_W)) stamp(
       .clk, .rst(rst_i), .valid(g_valid), .ready(g_ready), .message_type(app_message[g]),
       .app_control(app_control[g]), .epoch(tile_epoch[g]), .stamped_control(app_head_control));
   end else begin : NO_STAMP
     assign app_head_control=app_control[g];
   end
   assign ctl[g]   =sel_v ? vrtctl : sel_m ? mctl : sel_ep ? ertctl_x : app_head_control;"""


def generated():
    stage4 = (ROOT / S4).read_text(encoding="utf-8")
    prefix = "// TITAN S5 generated by scripts/titan/prepare_stage5.py. DO NOT EDIT.\n"
    result = {SUBSYSTEM: (prefix + replace_once(stage4, ANCHOR, WIRING, "S5.stamp")).encode()}
    stamp = (ROOT / STAMP).read_text(encoding="utf-8")
    mutations = json.loads((ROOT / CATALOG).read_bytes())
    if len(mutations) != 3 or len({entry["id"] for entry in mutations}) != 3:
        raise ValueError("Expected three distinct stamp mutations")
    for entry in mutations:
        name = entry["id"]
        if entry["file"] != STAMP or entry["expected"] != "KILL":
            raise ValueError(f"Unsupported mutant target or outcome: {name}")
        edited = replace_once(stamp, entry["anchor"], entry["replacement"], name)
        result[f"rtl/dual_lane/titan/s5/titan_stamp_mut_{name}.sv"] = (prefix + edited).encode()
    return result


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, raw in generated().items():
        path = ROOT / name
        if args.check:
            if path.read_bytes() != raw:
                raise ValueError(f"TITAN S5 generated content drift: {name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
    print("TITAN_S5_GENERATOR: PASS subsystem=1 checker_variants=3")


if __name__ == "__main__":
    main()
