"""Generate the D10 subsystem and isolated mutations, leaving old replay inputs intact."""
from argparse import ArgumentParser
import json
from pathlib import Path
from prepare_stage4 import ROOT, SUBSYSTEM as OLD, replace_once

BASE = "rtl/dual_lane/titan"
TRACKER = f"{BASE}/titan_epoch_tracker_r1.sv"
SUBSYSTEM = f"{BASE}/s4r/pq_noc_subsystem_p7_t1.sv"
CATALOG = "mutants/s4_mutants.json"
ANCHOR = "assign advance = authorized && !was_authorized;"
MUTATIONS = (
    ("revoke", "assign advance = authorized ^ was_authorized;", "EDGE_REVOKE"),
    ("held_high", "assign advance = authorized;", "EDGE_HELD"),
    ("trusted_fail", "assign advance = (authorized && !was_authorized) || trusted_fail;", "EDGE_TRUSTED"),
)


def outputs():
    source = (ROOT / OLD).read_text(encoding="utf-8")
    start = source.index("     logic auth_update, auth_grant;")
    end = source.index("   end else begin : NO_EPOCH", start)
    body = """     titan_epoch_tracker_r1 #(.EPOCH_W(EPOCH_W)) tracker(
       .clk, .rst(rst_i), .authorized(authorized[g]), .trusted_fail(t_fail),
       .epoch_o(tile_epoch[g]), .epoch_wrap_o(tile_epoch_wrap[g]));
"""
    answer = {SUBSYSTEM: ("// Generated by prepare_stage4r.py.\n" + source[:start] + body + source[end:]).encode()}
    items = []
    tracker = (ROOT / TRACKER).read_text(encoding="utf-8")
    for name, change, check in MUTATIONS:
        items.append(dict(id=name, file=TRACKER, anchor=ANCHOR, replacement=change,
                          targeted_check=check, expected="KILL"))
        answer[f"{BASE}/s4r/titan_epoch_mut_{name}.sv"] = replace_once(tracker, ANCHOR, change, name).encode()
    answer[CATALOG] = (json.dumps(items, indent=2) + "\n").encode()
    return answer


def main():
    parser = ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for rel, data in outputs().items():
        p = ROOT / rel
        if args.check:
            if p.read_bytes().replace(b"\r\n", b"\n") != data:
                raise ValueError(f"Generated source drift: {rel}")
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(data)
    print("TITAN S4R generator PASS")


if __name__ == "__main__":
    main()
