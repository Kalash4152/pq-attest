def header(src, edits):
    return (f'// GENERATED by scripts/prepare_p7_benches.py from NOC_PQATTEST.srcs/sim_1/new/{src} ({len(edits)} edits, contract sec. 9 P7\n'
            '// re-earn, docs/decisions/S2_REEARN_ADAPTATION.md). Do not edit by hand; edit the generator.\n')

def build(src, dst, edits):
    t = (T / src).read_text(encoding='utf-8')
    for old, new, n in edits:
        c = t.count(old)
        if c != n: raise SystemExit(f'prepare_p7_benches: {src}: expected {n} x {old[:70]!r}, found {c}')
        t = t.replace(old, new)
    return header(src, edits) + t

def main():
    bad = []
    for src, dst, edits in BENCHES:
        out = build(src, dst, edits)
        if '--check' in sys.argv:
            if not (T / dst).is_file() or (T / dst).read_text(encoding='utf-8') != out: bad.append(dst)
        else:
            (T / dst).write_text(out, encoding='utf-8', newline='\n'); print('wrote', dst)
    if '--check' in sys.argv:
        print('P7_BENCHES: ' + ('FAIL ' + ', '.join(bad) if bad else f'PASS ({len(BENCHES)} benches)')); sys.exit(1 if bad else 0)

if __name__ == '__main__': main()
