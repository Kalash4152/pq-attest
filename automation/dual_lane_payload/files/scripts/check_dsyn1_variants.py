"""D-SYN-1 variant check (registered job dsyn1_variants): provenance hashes, protected originals unchanged, and the
exact line diff of each variant against its original. Prints DSYN1_VARIANTS: PASS or exits non-zero."""
import difflib, hashlib, json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
S = ROOT / 'NOC_PQATTEST.srcs/sources_1/new'; D = ROOT / 'rtl/dual_lane'; E = ROOT / 'sim/dual_lane/dsyn1'
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
lines = lambda p: p.read_text(encoding='utf-8').replace('\r\n', '\n').split('\n')
EXPECTED = {
    'pq_keccak_iota.sv': ([], ['`ifndef SYNTHESIS', '`endif']),
    'SHA3_PAD.sv': (['for (int i = valid_bytes; i < RATE_BYTES; i++) begin', "padded_block[i*8 +: 8] = 8'h00;"],
                    ['for (int i = 0; i < RATE_BYTES; i++) begin', "if (i >= valid_bytes) padded_block[i*8 +: 8] = 8'h00;"]),
}
COPIES = {'SHA3_PAD.sv': ('sha3_pad', 'sha3_pad_orig_dsyn1'), 'pq_keccak_iota.sv': ('keccak_iota', 'keccak_iota_orig_dsyn1')}

def main():
    fails = []
    base = json.loads((ROOT / 'automation/dual_lane_payload/baseline_before.json').read_text())['files']
    prov = json.loads((D / 'variant_provenance.json').read_text())
    for name, (rem, add) in EXPECTED.items():
        o, v = S / name, D / name
        if sha(o) != base['NOC_PQATTEST.srcs/sources_1/new/' + name]: fails.append(f'{name}: protected original changed')
        if prov.get(name, {}).get('base') != sha(o) or prov[name].get('variant') != sha(v): fails.append(f'{name}: provenance mismatch')
        d = [l for l in difflib.ndiff(lines(o), lines(v)) if l[:2] in ('- ', '+ ')]
        got = ([l[2:].strip() for l in d if l[0] == '-'], [l[2:].strip() for l in d if l[0] == '+'])
        if got != (rem, add): fails.append(f'{name}: unexpected diff {got}')
        mod, ren = COPIES[name]; c = E / f'{ren}.sv'
        exp = ['// GENERATED by scripts/prepare_dsyn1_variants.py from the protected original; TB-only.'] + \
              [f'module {ren}' if l == f'module {mod}' else l for l in lines(o)]
        if lines(c) != exp: fails.append(f'{c.name}: TB-only copy differs from the renamed original')
        print(f'{name}: base {sha(o)[:12]} variant {sha(v)[:12]} removed={len(got[0])} added={len(got[1])}')
    for f in fails: print('FAIL', f)
    if fails: print(f'DSYN1_VARIANTS: FAIL n={len(fails)}'); sys.exit(1)
    print('DSYN1_VARIANTS: PASS (2 variants; diffs exactly as D-SYN-1; protected originals unchanged)')

if __name__ == '__main__': main()
