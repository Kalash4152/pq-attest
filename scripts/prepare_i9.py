def build():
    out = {}; prov = {}
    for dst, src, fn, tag in PLAN:
        raw = (ROOT / src).read_bytes(); text = raw.decode('utf-8').replace('\r\n', '\n')
        body = fn(text)
        if body.startswith('`timescale'):   # keep `timescale first
            first, rest = body.split('\n', 1); out[dst] = first + '\n' + hdr(src, tag) + rest
        else: out[dst] = hdr(src, tag) + body
        prov[dst] = dict(source=src, source_sha256=sha(raw), output_sha256=sha(out[dst].encode('utf-8')))
    return out, prov

