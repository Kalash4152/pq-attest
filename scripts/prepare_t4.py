"""T4 (DECISION_REGISTER T4; docs/decisions/T4_LOOKAHEAD_CONTRACT.md): cycle-identical lookahead routing in a router variant.
Generates, by exact-anchor edits that must match once, from pinned sources (hashes in rtl/dual_lane/t4_provenance.json):
  rtl/dual_lane/noc_fifo_la.sv              noc_fifo_la: noc_fifo + stored {route_valid, route_port} computed at write
  rtl/dual_lane/noc_router_datapath_la.sv   noc_router_datapath: input-VC FIFOs -> noc_fifo_la, head_route_* outputs
  rtl/dual_lane/allocator_la.sv             NOC_ALLOCATOR: stored route inputs instead of 15 noc_xy_routing on the heads
  rtl/dual_lane/noc_router_la.sv            noc_router (same name / ports as the protected router): wires the stored routes
and the equivalence copies (module names suffixed _t4eq, bench use only) under sim/t4/.
The protected sources are read, never written.
Usage: python scripts/prepare_t4.py   (writes the variants and the provenance); python scripts/check_t4.py (job t4_variant)"""
import hashlib, json, re
from pathlib import Path
import prepare_s3 as s3
ROOT = s3.ROOT; S = s3.S; D = s3.D; edit = s3.edit
CONTRACT = 'docs/decisions/T4_LOOKAHEAD_CONTRACT.md'
NL = chr(10)
sha = lambda b: hashlib.sha256(b).hexdigest()
PORTS = ['north', 'south', 'east', 'west', 'local']

def hdr(src, tag):
    return f'// GENERATED by scripts/prepare_t4.py from {src} ({tag}, {CONTRACT}). Do not edit.' + NL

def fifo_la(t):
    t = edit(t, [
        ('module noc_fifo #(', 'module noc_fifo_la #('),
        ('    output logic credit_valid\n);',
         '    output logic credit_valid,\n\n'
         '    // T4 lookahead: this router\'s coordinate (constant) and the route of the visible flit, computed when the flit\n'
         '    // was written. Empty: the route of the all-zero flit, exactly what the original allocator computes from rd_flit = \'0.\n'
         '    input  noc_pkg::coord_t   cur_coord,\n'
         '    output noc_pkg::port_id_t rd_route_port,\n'
         '    output logic              rd_route_valid\n);'),
        ('    flit_t fifo_mem [0:DEPTH-1];\n',
         '    flit_t fifo_mem [0:DEPTH-1];\n\n'
         '    // T4: route stored beside every entry (same pointers). Header serialisation as NOC_ALLOCATOR: dest_x = flit_data[31:29],\n'
         '    // dest_y = flit_data[28:26].\n'
         '    (* ram_style = "distributed" *)\n'
         '    logic [$bits(port_id_t):0] route_mem [0:DEPTH-1];\n'
         '    coord_t   wr_dest, zero_dest;\n'
         '    port_id_t wr_route_port, zero_route_port;\n'
         '    logic     wr_route_valid, zero_route_valid;\n'
         '    always_comb begin\n'
         '        wr_dest.x = wr_flit.flit_data[31:29];\n'
         '        wr_dest.y = wr_flit.flit_data[28:26];\n'
         "        zero_dest = '0;\n"
         '    end\n'
         '    noc_xy_routing u_wr_route   (.current_coord(cur_coord), .dest_coord(wr_dest),   .route_port(wr_route_port),   .route_valid(wr_route_valid));\n'
         '    noc_xy_routing u_zero_route (.current_coord(cur_coord), .dest_coord(zero_dest), .route_port(zero_route_port), .route_valid(zero_route_valid));\n'),
        ('            rd_flit = fifo_mem[rd_ptr];\n',
         '            begin rd_flit = fifo_mem[rd_ptr]; {rd_route_valid, rd_route_port} = route_mem[rd_ptr]; end\n'),
        ("            rd_flit = '0;\n",
         "            begin rd_flit = '0; rd_route_valid = zero_route_valid; rd_route_port = zero_route_port; end\n"),
        ('                fifo_mem[wr_ptr] <= wr_flit;\n',
         '                fifo_mem[wr_ptr] <= wr_flit;\n'
         '                route_mem[wr_ptr] <= {wr_route_valid, wr_route_port};\n')], 'fifo_la')
    return t

FIFO_RE = re.compile(r'    noc_fifo #\(\.DEPTH \(VC(\d)_DEPTH\)\) (north|south|east|west|local)_vc(\d)_fifo \(\n')

def datapath_la(t):
    t = edit(t, [
        ('    input  logic rst,\n', '    input  logic rst,\n\n    input  noc_pkg::coord_t cur_coord,   // T4: this router\'s coordinate (constant)\n'),
        ('    output noc_pkg::flit_t head_local_vc2,\n',
         '    output noc_pkg::flit_t head_local_vc2,\n\n'
         '    // T4: stored route of every visible head flit, index = noc_pkg::make_input_vc(port, vc)\n'
         '    output noc_pkg::port_id_t head_route_port  [noc_pkg::NUM_INPUT_VCS],\n'
         '    output logic              head_route_valid [noc_pkg::NUM_INPUT_VCS],\n')], 'datapath_la')
    found = FIFO_RE.findall(t)
    if len(found) != 15 or any(a != c for a, _, c in found): raise SystemExit(f'datapath_la: expected 15 input-VC FIFOs, found {found}')
    t = FIFO_RE.sub(lambda m: (f'    noc_fifo_la #(.DEPTH (VC{m[1]}_DEPTH)) {m[2]}_vc{m[3]}_fifo (\n'
                               f'        .cur_coord    (cur_coord),\n'
                               f'        .rd_route_port  (rp_{m[2]}_vc{m[3]}),\n'
                               f'        .rd_route_valid (rv_{m[2]}_vc{m[3]}),\n'), t)
    wires = '    import noc_pkg::*;\n\n    // T4: stored routes of the 15 input-VC FIFOs (declared before the FIFO instances)\n'
    wires += ''.join(f'    noc_pkg::port_id_t rp_{p}_vc{v}; logic rv_{p}_vc{v};\n' for p in PORTS for v in range(3))
    t = edit(t, [('    import noc_pkg::*;\n', wires)], 'datapath_la wires')
    decl = '    // T4: stored routes, indexed as the router indexes head_flit\n    always_comb begin\n'
    decl += ''.join(f'        head_route_port [noc_pkg::make_input_vc(noc_pkg::PORT_{p.upper()},{v})] = rp_{p}_vc{v};\n'
                    f'        head_route_valid[noc_pkg::make_input_vc(noc_pkg::PORT_{p.upper()},{v})] = rv_{p}_vc{v};\n' for p in PORTS for v in range(3))
    decl += '    end\n\nendmodule'
    if t.count('\nendmodule') != 1: raise SystemExit('datapath_la: endmodule not unique')
    return t.replace('\nendmodule', '\n' + decl, 1)

def allocator_la(t):
    return edit(t, [
        ('    input  noc_pkg::flit_t               head_flit [NUM_INPUT_VCS],\n',
         '    input  noc_pkg::flit_t               head_flit [NUM_INPUT_VCS],\n\n'
         '    // T4: route of every head flit, computed when it was written into its FIFO (= noc_xy_routing on head_flit)\n'
         '    input  noc_pkg::port_id_t            head_route_port  [NUM_INPUT_VCS],\n'
         '    input  logic                         head_route_valid [NUM_INPUT_VCS],\n'),
        ('            // A1: module name is lowercase noc_xy_routing.\n'
         '            noc_xy_routing u_xy_routing (\n'
         '                .current_coord (cur_coord),\n'
         '                .dest_coord    (dest_coord[g_vc]),\n'
         '                .route_port    (route_port[g_vc]),\n'
         '                .route_valid   (route_valid[g_vc])\n'
         '            );\n',
         '            // T4 lookahead: the route was computed at FIFO write (noc_fifo_la); same value, off the read path.\n'
         '            assign route_port [g_vc] = head_route_port [g_vc];\n'
         '            assign route_valid[g_vc] = head_route_valid[g_vc];\n')], 'allocator_la')

def router_la(t):
    return edit(t, [
        ('    logic  fifo_empty [IVCS];\n',
         '    logic  fifo_empty [IVCS];\n'
         '    port_id_t head_route_port  [IVCS];   // T4: stored routes (datapath -> allocator)\n'
         '    logic     head_route_valid [IVCS];\n'),
        ('    noc_router_datapath u_datapath (\n        .clk (clk), .rst (rst),\n',
         '    noc_router_datapath u_datapath (\n        .clk (clk), .rst (rst),\n'
         '        .cur_coord (current_coord), .head_route_port (head_route_port), .head_route_valid (head_route_valid),   // T4\n'),
        ('        .head_flit   (head_flit),\n',
         '        .head_flit   (head_flit),\n'
         '        .head_route_port  (head_route_port),    // T4\n'
         '        .head_route_valid (head_route_valid),\n')], 'router_la')

EQ = [('module noc_router #(', 'module noc_router_t4eq #('), ('    noc_router_datapath u_datapath (', '    noc_router_datapath_t4eq u_datapath ('),
      ('    NOC_ALLOCATOR u_allocator (', '    NOC_ALLOCATOR_t4eq u_allocator ('),
      ('module noc_router_datapath (', 'module noc_router_datapath_t4eq ('), ('module NOC_ALLOCATOR #(', 'module NOC_ALLOCATOR_t4eq #(')]
def eqname(t, what):
    return edit(t, [(a, b) for a, b in EQ if a in t], what)

PLAN = [(D + 'noc_fifo_la.sv',             S + 'NOC_FIFO.sv',     fifo_la,      'T4 FIFO'),
        (D + 'noc_router_datapath_la.sv',  S + 'NOC_DATAPTAH.sv', datapath_la,  'T4 datapath'),
        (D + 'allocator_la.sv',            S + 'allocator.sv',    allocator_la, 'T4 allocator'),
        (D + 'noc_router_la.sv',           S + 'noc_router.sv',   router_la,    'T4 router'),
        ('sim/t4/noc_router_datapath_t4eq.sv', S + 'NOC_DATAPTAH.sv', lambda t: eqname(datapath_la(t), 'eq dp'),  'T4 datapath, equivalence copy'),
        ('sim/t4/allocator_t4eq.sv',           S + 'allocator.sv',    lambda t: eqname(allocator_la(t), 'eq al'), 'T4 allocator, equivalence copy'),
        ('sim/t4/noc_router_t4eq.sv',          S + 'noc_router.sv',   lambda t: eqname(router_la(t), 'eq r'),     'T4 router, equivalence copy')]

def build():
    out = {}; prov = {}
    for dst, src, fn, tag in PLAN:
        raw = (ROOT / src).read_bytes(); text = raw.decode('utf-8').replace('\r\n', '\n')
        out[dst] = hdr(src, tag) + fn(text)
        prov[dst] = dict(source=src, source_sha256=sha(raw), output_sha256=sha(out[dst].encode('utf-8')))
    return out, prov

def main():
    out, prov = build()
    for dst, text in out.items():
        (ROOT / dst).parent.mkdir(parents=True, exist_ok=True); (ROOT / dst).write_bytes(text.encode('utf-8'))
    (ROOT / D / 't4_provenance.json').write_text(json.dumps(dict(schema=1, contract=CONTRACT, files=prov), indent=2) + NL, encoding='utf-8')
    for dst in out: print('wrote', dst)

if __name__ == '__main__': main()
