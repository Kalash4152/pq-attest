"""B-2 step a (M-F1 rev 7 R7.8.1): generate the TB-only renamed copy of the PRE-TRIM rtl/dual_lane/noc_l2_auth.sv for the
trim equivalence bench, and record provenance of the trimmed file. The pre-trim source is the git blob at commit 90e8dca,
pinned by SHA-256 (the file is edited in place by the trim; the old text is never reconstructed by hand). Reads git only."""
import hashlib, json, subprocess
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
D = ROOT / 'rtl/dual_lane'; E = ROOT / 'sim/dual_lane/l2trim'
BASE_COMMIT, BASE_SHA = '90e8dca', 'f56ac1f56eada1bdcf94a61f5f40aa994aef58eab5d10e12b98f7275d96a91e3'
HEADER = '// GENERATED by scripts/prepare_l2trim.py from rtl/dual_lane/noc_l2_auth.sv @ 90e8dca (pre-trim); TB-only.\n'
sha = lambda b: hashlib.sha256(b).hexdigest()
def base_text():
    b = subprocess.check_output(['git', 'show', f'{BASE_COMMIT}:rtl/dual_lane/noc_l2_auth.sv'], cwd=ROOT)
    if sha(b) != BASE_SHA: raise SystemExit('pre-trim blob hash mismatch')
    t = b.decode('utf-8')
    if t.count('module noc_l2_auth #(\n') != 1: raise SystemExit('module anchor')
    return t
def expected_copy():
    return HEADER + base_text().replace('module noc_l2_auth #(\n', 'module noc_l2_auth_orig_l2trim #(\n')
def main():
    E.mkdir(parents=True, exist_ok=True)
    (E / 'noc_l2_auth_orig_l2trim.sv').write_text(expected_copy(), encoding='utf-8', newline='\n')
    prov = json.loads((D / 'variant_provenance.json').read_text())
    prov['noc_l2_auth.sv'] = dict(base=BASE_SHA, base_commit=BASE_COMMIT, variant=sha((D / 'noc_l2_auth.sv').read_bytes()),
                                  decision='docs/decisions/M-F1-interface-freeze.md R7.8.1 (trims T1, T2); DECISION_REGISTER D-AREA-1')
    (D / 'variant_provenance.json').write_text(json.dumps(prov, indent=2) + '\n', encoding='utf-8', newline='\n')
    print('L2TRIM: provenance', prov['noc_l2_auth.sv'])
if __name__ == '__main__': main()
