"""Generate tb_noc_perf.sv: the validated tb_noc_n81 per-instance NI binding scaffold
(XSim assertion-sampling workaround, copied verbatim) plus scripts/perf_bench_body.sv.inc.

    python scripts/prepare_perf_bench.py          # (re)write the bench
    python scripts/prepare_perf_bench.py --check  # exit 1 if the committed bench is stale
"""
import sys
from pathlib import Path
R=Path(__file__).resolve().parents[1]
OUT=R/'NOC_PQATTEST.srcs/sim_1/new/tb_noc_perf.sv'

def generate():
    s=(R/'NOC_PQATTEST.srcs/sim_1/new/tb_noc_n81.sv').read_text()
    start=s.index('module tb_noc_n81 #(')
    end=s.index('    // Check bookkeeping')
    scaffold=s[start:end].rsplit('    //-------------------------------------------------------------------------',1)[0]
    # The per-instance binding must be carried unchanged (XSim workaround, 2026-10-01).
    for anchor in ['XSim workaround (2026-10-01)','for (genvar g = 0; g < NT; g++) begin : GN',
                   'assign l_noc_rx_valid = m_out_valid[g];','assign m_out_ready[g] = l_noc_rx_ready;',
                   'noc_network_interface #(']:
        if scaffold.count(anchor)!=1: raise SystemExit('scaffold anchor missing or duplicated: '+anchor)
    scaffold=scaffold.replace('module tb_noc_n81','module tb_noc_perf').replace('always #5 clk','always #10 clk')
    probes=s[s.index('    logic r_idle [NT];'):s.index('    wire lk_r0e')]
    body=(R/'scripts/perf_bench_body.sv.inc').read_text()
    head=('// GENERATED by scripts/prepare_perf_bench.py from tb_noc_n81.sv (scaffold) and\n'
          '// scripts/perf_bench_body.sv.inc. Do not edit by hand; edit the generator inputs.\n')
    return head+'`timescale 1ns/1ps\n`define N81_W 64\n`define N81_WDE 1\n`define N81_RUNS 7\n'+scaffold+probes+body

def main(argv):
    text=generate()
    if '--check' in argv:
        ok=OUT.is_file() and OUT.read_bytes()==text.encode()
        print('PERF_BENCH_UP_TO_DATE' if ok else 'PERF_BENCH_STALE'); return 0 if ok else 1
    OUT.write_text(text,newline='\n'); print('wrote',OUT.relative_to(R).as_posix()); return 0

if __name__=='__main__': raise SystemExit(main(sys.argv[1:]))
