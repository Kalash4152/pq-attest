"""B-3 step b (M-F1 rev 7 R7.8.2, D): KDF and tag time-multiplexed on ONE kmac128 inside the endpoint controller and
inside the RoT verifier. Generates, from the PROTECTED originals (hashes pinned by the payload baseline):
  rtl/dual_lane/pq_kdf_xk.sv               pq_kdf with its kmac128 replaced by an external request port (xk_*)
  rtl/dual_lane/pq_attestation_tag_xk.sv   pq_attestation_tag likewise
  rtl/dual_lane/pq_attest_protocol.sv      controller variant: the two engines above + one pq_kmac_share
The shared engine itself is hand-written (rtl/dual_lane/pq_kmac_share.sv); the verifier is edited in place
(rtl/dual_lane/pq_rot_verifier.sv, a dual-lane original). Every text edit is an exact-anchor replacement that must
match once; the instance port lines the s8 mutants anchor on are kept verbatim. Provenance -> variant_provenance.json."""
import hashlib, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
S = ROOT / 'NOC_PQATTEST.srcs/sources_1/new'; D = ROOT / 'rtl/dual_lane'
sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()
HDR = '// GENERATED by scripts/prepare_kshare.py from the protected original {src} (D, M-F1 rev 7 R7.8.2). Do not edit.\n'

def edit(text, reps, what):
    for a, b in reps:
        if text.count(a) != 1: raise SystemExit(f'{what}: anchor not unique/found: {a[:70]!r}')
        text = text.replace(a, b)
    return text

def cut_instance(text, head, what):
    """Remove the kmac128 instance that starts at `head` up to its closing ');' line; return (before, after)."""
    i = text.index(head); j = text.index('\n    );\n', i) + len('\n    );\n')
    if text.count(head) != 1: raise SystemExit(f'{what}: kmac128 instance anchor not unique')
    return text[:i], text[j:]

def kdf_xk(t):
    t = edit(t, [('module pq_kdf\n', 'module pq_kdf_xk\n'),
                 ('    output logic                         done\n);',
                  '    output logic                         done,\n\n'
                  '    // D: external KMAC request port to pq_kmac_share (the internal kmac128 is removed).\n'
                  '    output logic                         xk_start,\n'
                  '    output logic [255:0]                 xk_key,\n'
                  '    output logic [5:0]                   xk_key_len,\n'
                  '    output logic [319:0]                 xk_msg,         // MSG_BYTES_KDF = 40\n'
                  '    output logic [5:0]                   xk_msg_len,\n'
                  '    output logic                         xk_out_len_sel,\n'
                  '    input  logic [255:0]                 xk_tag,\n'
                  '    input  logic                         xk_busy,\n'
                  '    input  logic                         xk_done\n);')], 'pq_kdf')
    a, b = cut_instance(t, '    kmac128 #(\n        .KEY_BYTES    (ROOT_SECRET_BYTES),      // 32\n', 'pq_kdf')
    return a + ('    // D: request bundle to the shared kmac128 (same values the removed instance received).\n'
                '    assign xk_start       = kmac_start;\n'
                '    assign xk_key         = root_q;\n'
                '    assign xk_key_len     = 6\'d32;\n'
                '    assign xk_msg         = kdf_msg;\n'
                '    assign xk_msg_len     = kdf_msg_len;\n'
                '    assign xk_out_len_sel = (key_sel_q == KDF_LEN_256) ? KMAC_L_256 : KMAC_L_128;\n'
                '    assign kmac_tag       = xk_tag;\n'
                '    assign kmac_busy      = xk_busy;\n'
                '    assign kmac_done      = xk_done;\n') + b

def tag_xk(t):
    t = edit(t, [('module pq_attestation_tag\n', 'module pq_attestation_tag_xk\n'),
                 ('    output logic                         err           // pulses with done\n);',
                  '    output logic                         err,          // pulses with done\n\n'
                  '    // D: external KMAC request port to pq_kmac_share (the internal kmac128 is removed).\n'
                  '    output logic                         xk_start,\n'
                  '    output logic [255:0]                 xk_key,\n'
                  '    output logic [5:0]                   xk_key_len,\n'
                  '    output logic [127:0]                 xk_custom,\n'
                  '    output logic [4:0]                   xk_custom_len,\n'
                  '    output logic [519:0]                 xk_msg,         // TAG_MSG_BYTES = 65\n'
                  '    output logic [6:0]                   xk_msg_len,\n'
                  '    output logic                         xk_out_len_sel,\n'
                  '    input  logic [255:0]                 xk_tag,\n'
                  '    input  logic                         xk_busy,\n'
                  '    input  logic                         xk_done\n);')], 'pq_attestation_tag')
    a, b = cut_instance(t, '    kmac128 #(\n        .KEY_BYTES    (TILE_KEY_BYTES),      // 32\n', 'pq_attestation_tag')
    return a + ('    // D: request bundle to the shared kmac128 (same values the removed instance received).\n'
                '    assign xk_start       = kmac_start_q;\n'
                '    assign xk_key         = key_q;\n'
                '    assign xk_key_len     = kmac_key_len;\n'
                '    assign xk_custom      = kmac_custom_in;\n'
                '    assign xk_custom_len  = kmac_custom_len;\n'
                '    assign xk_msg         = tag_msg;\n'
                '    assign xk_msg_len     = tag_msg_len;\n'
                '    assign xk_out_len_sel = (len_sel_q == TAG_LEN_256) ? KMAC_L_256 : KMAC_L_128;\n'
                '    assign kmac_tag       = xk_tag;\n'
                '    assign kmac_busy      = xk_busy;\n'
                '    assign kmac_done      = xk_done;\n') + b

KDF_PORTS = ('        .xk_start(ka_start), .xk_key(ka_key), .xk_key_len(ka_key_len), .xk_msg(ka_msg), .xk_msg_len(ka_msg_len),\n'
             '        .xk_out_len_sel(ka_len_sel), .xk_tag(ks_tag), .xk_busy(ks_busy), .xk_done(ks_done),\n')
TAG_PORTS = ('        .xk_start(kb_start), .xk_key(kb_key), .xk_key_len(kb_key_len), .xk_custom(kb_custom),\n'
             '        .xk_custom_len(kb_custom_len), .xk_msg(kb_msg), .xk_msg_len(kb_msg_len), .xk_out_len_sel(kb_len_sel),\n'
             '        .xk_tag(ks_tag), .xk_busy(ks_busy), .xk_done(ks_done),\n')
SHARE = ('    //=========================================================================\n'
         '    // D (M-F1 rev 7 R7.8.2): ONE kmac128 shared by the KDF and the tag. The FSM below runs them strictly in\n'
         '    // sequence (S_KDF_* before S_TAG_*), so they never compete; pq_kmac_share asserts it.\n'
         '    //=========================================================================\n'
         '    logic         ka_start, kb_start, ka_len_sel, kb_len_sel, ks_busy, ks_done;\n'
         '    logic [255:0] ka_key, kb_key, ks_tag;\n'
         '    logic [5:0]   ka_key_len, kb_key_len, ka_msg_len;\n'
         '    logic [319:0] ka_msg;\n'
         '    logic [127:0] kb_custom;\n'
         '    logic [4:0]   kb_custom_len;\n'
         '    logic [519:0] kb_msg;\n'
         '    logic [6:0]   kb_msg_len;\n'
         '    pq_kmac_share u_pq_kmac_share (\n'
         '        .clk, .rst_n,\n'
         '        .a_start(ka_start), .a_key(ka_key), .a_key_len(ka_key_len), .a_msg(ka_msg), .a_msg_len(ka_msg_len), .a_out_len_sel(ka_len_sel),\n'
         '        .b_start(kb_start), .b_key(kb_key), .b_key_len(kb_key_len), .b_custom(kb_custom), .b_custom_len(kb_custom_len),\n'
         '        .b_msg(kb_msg), .b_msg_len(kb_msg_len), .b_out_len_sel(kb_len_sel),\n'
         '        .tag_out(ks_tag), .busy(ks_busy), .done(ks_done));\n\n')

def controller(t):
    return edit(t, [
        ('    pq_kdf u_pq_kdf (\n', SHARE + '    pq_kdf_xk u_pq_kdf (\n'),
        ('        .derived_key      (kdf_derived_key),\n', KDF_PORTS + '        .derived_key      (kdf_derived_key),\n'),
        ('    pq_attestation_tag u_pq_attestation_tag (\n', '    pq_attestation_tag_xk u_pq_attestation_tag (\n'),
        ('        .tag           (tag),\n', TAG_PORTS + '        .tag           (tag),\n'),
    ], 'pq_attest_protocol')

SOURCES = {'pq_kdf.sv': ('pq_kdf_xk.sv', kdf_xk), 'pqattest_stg7.sv': ('pq_attestation_tag_xk.sv', tag_xk),
           'pq_attest_protocol.sv': ('pq_attest_protocol.sv', controller)}

def expected():
    base = json.loads((ROOT / 'automation/dual_lane_payload/baseline_before.json').read_text())['files']
    out = {}
    for src, (dst, fn) in SOURCES.items():
        p = S / src
        if sha(p) != base['NOC_PQATTEST.srcs/sources_1/new/' + src]: raise SystemExit(f'protected original changed: {src}')
        out[dst] = (src, HDR.format(src=src) + fn(p.read_text(encoding='utf-8')))
    return out

def main():
    prov = json.loads((D / 'variant_provenance.json').read_text())
    for dst, (src, text) in expected().items():
        (D / dst).write_text(text, encoding='utf-8', newline='\n')
        prov[dst] = dict(base=sha(S / src), base_file='NOC_PQATTEST.srcs/sources_1/new/' + src, variant=sha(D / dst),
                         decision='M-F1 rev 7 R7.8.2 (D); DECISION_REGISTER D-AREA-1', generator='scripts/prepare_kshare.py')
    prov['pq_rot_verifier.sv'] = dict(base='2decf1c97e6059d810c98f42193bac7c279e480ebc6bd812fc5a07b081d6ecdf', base_commit='10b217a', note='dual-lane original edited in place', variant=sha(D / 'pq_rot_verifier.sv'),
                                      decision='M-F1 rev 7 R7.8.2 (D)')
    (D / 'variant_provenance.json').write_text(json.dumps(prov, indent=2) + '\n', encoding='utf-8', newline='\n')
    print('KSHARE: generated', ', '.join(expected()))

if __name__ == '__main__': main()
