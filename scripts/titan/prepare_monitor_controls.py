"""Generate the three deliberately faulty, simulation-only checker variants."""
from pathlib import Path
import sys

DIRECTORY = Path("rtl/dual_lane/titan")
SOURCE = DIRECTORY / "titan_finality_monitor.sv"
EDITS = {
    "p1": (
        "if (txn[commit_src][commit_tag].state == EMPTY ||",
        "if (1'b0 && (txn[commit_src][commit_tag].state == EMPTY ||",
        "shadow_epoch[commit_src]) begin // TITAN_P1_CHECK",
        "shadow_epoch[commit_src])) begin // TITAN_P1_CHECK",
    ),
    "tag": ("tag = int'(issue_tag[tile]); // TITAN_TAG_INDEX",
            "tag = int'(issue_tag[tile] ^ 1'b1); // TITAN_TAG_INDEX"),
    "reset": ("txn[tile][tag] = '0; // TITAN_RESET_TABLE",
              "if ($isunknown(txn[tile][tag].state)) txn[tile][tag] = '0; // TITAN_RESET_TABLE"),
}


def main():
    source = SOURCE.read_bytes().decode().replace("\r\n", "\n")
    check_only = sys.argv[1:] == ["--check"]
    for name, edits in EDITS.items():
        changed = source
        for before, after in zip(edits[::2], edits[1::2]):
            if changed.count(before) != 1:
                raise ValueError(f"{name}: missing or ambiguous checker edit")
            changed = changed.replace(before, after, 1)
        path = DIRECTORY / f"titan_mon_mut_{name}.sv"
        raw = (f"// GENERATED by scripts/titan/prepare_monitor_controls.py ({name}). Simulation only.\n"
               + changed).encode()
        if check_only:
            if path.read_bytes() != raw:
                raise ValueError(f"{path} does not match its one controlled fault")
        else:
            path.write_bytes(raw)
    print("TITAN_MON_VARIANTS: PASS variants=3")


if __name__ == "__main__":
    main()
