"""Generate D10-integrated S5 without overwriting the first S5 inputs."""
from argparse import ArgumentParser
from prepare_stage4r import SUBSYSTEM as REVISED_S4
from prepare_stage5 import ROOT, ANCHOR, WIRING, replace_once

SUBSYSTEM = "rtl/dual_lane/titan/s5r/pq_noc_subsystem_p7_t1.sv"


def main():
    parser = ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    raw = (ROOT / REVISED_S4).read_text(encoding="utf-8")
    text = "// Generated by scripts/titan/prepare_stage5r.py.\n"
    output = (text + replace_once(raw, ANCHOR, WIRING, "S5R.stamp")).encode()
    target = ROOT / SUBSYSTEM
    if args.check:
        if target.read_bytes().replace(b"\r\n", b"\n") != output:
            raise ValueError("S5R subsystem differs from the pinned D10 and S5 sources")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(output)
    print("TITAN S5R generator PASS")


if __name__ == "__main__":
    main()
