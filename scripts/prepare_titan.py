"""Generate isolated TITAN variants from the pinned B0 I-9 sources."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LANE = Path("rtl/dual_lane")
PROVENANCE = LANE / "titan_provenance.json"
MODULES = (
    "noc_network_interface_p7",
    "noc_l2_auth_p7",
    "noc_l2_p7_pair",
    "pq_noc_subsystem_p7",
)
EDITS = ()


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def replace_once(text, anchor, replacement, label):
    matches = text.count(anchor)
    if matches != 1:
        raise ValueError(f"{label}: anchor matched {matches} times, expected one")
    return text.replace(anchor, replacement, 1)


def variant_map():
    return {f"rtl/dual_lane/{m}_i9.sv": f"rtl/dual_lane/{m}_t1.sv" for m in MODULES}


def build(root=ROOT):
    manifest = json.loads((root / PROVENANCE).read_text(encoding="utf-8"))
    mapping = variant_map()
    if manifest["schema"] != 1 or set(manifest["input_sha256"]) != set(mapping):
        raise ValueError("TITAN provenance does not match the four required inputs")
    outputs = {}
    applied = set()
    for src, dst in mapping.items():
        raw = (root / src).read_bytes()
        digest = sha(raw)
        if digest != manifest["input_sha256"][src]:
            raise ValueError(f"TITAN input hash mismatch: {src}")
        body = raw.decode("utf-8")
        for name, target, anchor, replacement in EDITS:
            if target == src:
                if name in applied:
                    raise ValueError(f"Duplicate edit: {name}")
                body = replace_once(body, anchor, replacement, name)
                applied.add(name)

        header = f"// GENERATED by scripts/prepare_titan.py from {src} sha256 {digest}. DO NOT EDIT.\n"
        if body.startswith("`timescale"):
            first, rest = body.split("\n", 1)
            body = first + "\n" + header + rest
        else:
            body = header + body
        outputs[dst] = body.encode("utf-8")
    if len(applied) != len(EDITS):
        raise ValueError("TITAN edit list contains unknown targets or duplicate names")
    return outputs


def main():
    for rel, raw in build().items():
        (ROOT / rel).write_bytes(raw)
    print(f"TITAN_GENERATE: PASS files={len(MODULES)} named_edits={len(EDITS)}")


if __name__ == "__main__":
    main()
