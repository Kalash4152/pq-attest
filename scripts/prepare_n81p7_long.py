"""N-8.1 P7 LONG counterfactual fixture (DECISION_REGISTER S2-N81-P7; docs/decisions/S2_REEARN_ADAPTATION.md "Resume
qualification corrections"): copies of rtl/dual_lane/NOC_PKG.sv and rtl/dual_lane/noc_p7_pkg.sv in which MEM_WR_REQ
carries 16 payload words (17 wire flits, more than the 12-entry eject FIFO) and the per-packet elaboration guard is
omitted. TEST-ONLY: used only by the n81p7_long* jobs, in place of (never next to) the production packages. Production
packages, framing and the production guard are unchanged.
Usage: python scripts/prepare_n81p7_long.py [--check]"""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'sim/dual_lane/n81p7_long'
HDR = ('// GENERATED by scripts/prepare_n81p7_long.py from rtl/dual_lane/{src}. COUNTERFACTUAL TEST FIXTURE, not P7 traffic:\n'
       '// MEM_WR_REQ = 16 payload words; the per-packet elaboration guard is omitted. Used only by the n81p7_long* jobs.\n')

def build():
    pkg = (ROOT / 'rtl/dual_lane/NOC_PKG.sv').read_text(encoding='utf-8')
    a = "MSG_MEM_WR_REQ:       return 5'd2;"
    if pkg.count(a) != 1: raise SystemExit('prepare_n81p7_long: payload anchor changed')
    pkg = pkg.replace(a, "MSG_MEM_WR_REQ:       return 5'd16; // COUNTERFACTUAL ONLY")
    prof = (ROOT / 'rtl/dual_lane/noc_p7_pkg.sv').read_text(encoding='utf-8')
    if prof.count('p7_packet_bound_check_t') != 2: raise SystemExit('prepare_n81p7_long: guard anchors changed')
    prof = '\n'.join(l for l in prof.splitlines() if 'p7_packet_bound_check_t' not in l) + '\n'
    return {'NOC_PKG_cf.sv': HDR.format(src='NOC_PKG.sv') + pkg, 'noc_p7_pkg_cf.sv': HDR.format(src='noc_p7_pkg.sv') + prof}

def main():
    files = build(); bad = []
    for name, text in files.items():
        p = OUT / name
        if '--check' in sys.argv:
            if not p.is_file() or p.read_text(encoding='utf-8') != text: bad.append(name)
        else:
            OUT.mkdir(parents=True, exist_ok=True); p.write_text(text, encoding='utf-8', newline='\n'); print('wrote', p.relative_to(ROOT))
    if '--check' in sys.argv:
        print('N81P7_LONG: ' + ('FAIL ' + ', '.join(bad) if bad else 'PASS')); sys.exit(1 if bad else 0)

if __name__ == '__main__': main()
