"""D-SYN-2: record provenance for the hand-written rtl/dual_lane/pq_measurement.sv variant (Option 2, byte-serial
assembly) and generate the TB-only renamed copy of the protected original for the equivalence bench. Reads only."""
import hashlib, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
S = ROOT / 'NOC_PQATTEST.srcs/sources_1/new'; D = ROOT / 'rtl/dual_lane'; E = ROOT / 'sim/dual_lane/dsyn2'
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
def main():
    base = json.loads((ROOT / 'automation/dual_lane_payload/baseline_before.json').read_text())['files']
    o = S / 'pq_measurement.sv'
    if sha(o) != base['NOC_PQATTEST.srcs/sources_1/new/pq_measurement.sv']: raise SystemExit('protected original changed')
    t = o.read_text(encoding='utf-8')
    if t.count('module pq_measurement\n') != 1: raise SystemExit('module anchor')
    E.mkdir(parents=True, exist_ok=True)
    (E / 'pq_measurement_orig_dsyn2.sv').write_text('// GENERATED by scripts/prepare_dsyn2.py from the protected original; TB-only.\n'
        + t.replace('module pq_measurement\n', 'module pq_measurement_orig_dsyn2\n'), encoding='utf-8', newline='\n')
    prov = json.loads((D / 'variant_provenance.json').read_text())
    prov['pq_measurement.sv'] = dict(base=sha(o), variant=sha(D / 'pq_measurement.sv'), decision='docs/decisions/D-SYN-2-measurement-architecture.md')
    (D / 'variant_provenance.json').write_text(json.dumps(prov, indent=2) + '\n', encoding='utf-8', newline='\n')
    print('DSYN2: provenance', prov['pq_measurement.sv'])
if __name__ == '__main__': main()
