"""Write a Vivado Tcl script that builds a SEPARATE GUI simulation project for one registered dual-lane job.

The main NOC_PQATTEST.xpr holds only the production sources. The P7 work lives in rtl/dual_lane/ variants that share
module names with production files (NOC_PKG, pq_measurement, ...), so it must never be added to that project
(CLAUDE.md: a variant and its original never share a source list). This script copies a job's exact registered source
list, defines, generics, include dirs and time limit from scripts/dual_lane_jobs.json into its own project under
vivado_sim/<job>/. Sources are referenced in place (not copied). Not evidence: registered results come only from
scripts/dual_lane.py.

Usage: python scripts/make_vivado_sim_project.py <job_id> [<job_id> ...]   -> scripts/vivado_sim_<job_id>.tcl
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JOBS = json.loads((ROOT / 'scripts' / 'dual_lane_jobs.json').read_text())['jobs']

def tcl_path(rel):
    return '"' + (ROOT / rel).resolve().as_posix() + '"'

def emit(job_id):
    job = next((j for j in JOBS if j['id'] == job_id), None)
    if job is None: raise SystemExit(f'unknown job {job_id}')
    if job['kind'] != 'simulation': raise SystemExit(f'{job_id} is a {job["kind"]} job, not a simulation')
    if job.get('mutant'): raise SystemExit(f'{job_id} is a mutant job (source edited at run time); pick its unmutated bench')
    proj_dir = (ROOT / 'vivado_sim' / job_id).as_posix()
    srcs = [s for s in job['sources'] if '/sim_1/' not in s and not Path(s).name.startswith('tb_')]
    tbs = [s for s in job['sources'] if s not in srcs]
    lines = [
        f'# Generated by scripts/make_vivado_sim_project.py from dual_lane_jobs.json job "{job_id}". Do not edit by hand.',
        f'# Separate project; NOC_PQATTEST.xpr is not touched. Run: vivado -mode gui -source <this file>  (or Tcl console: source <this file>)',
        f'create_project -force {job_id}_sim "{proj_dir}" -part xc7a100tcsg324-1',
        'set_property target_language Verilog [current_project]',
        'set_property simulator_language Mixed [current_project]',
        'add_files -norecurse -fileset sources_1 [list ' + ' '.join(tcl_path(s) for s in srcs) + ']',
        'add_files -norecurse -fileset sim_1 [list ' + ' '.join(tcl_path(s) for s in tbs) + ']',
        'set vfiles [get_files -quiet -of_objects [get_filesets {sources_1 sim_1}] -filter {FILE_TYPE == Verilog}]',
        'if {[llength $vfiles]} { set_property file_type SystemVerilog $vfiles }',
        'set_property source_mgmt_mode None [current_project]',
        'update_compile_order -fileset sources_1',
        f'set_property top {job["top"]} [get_filesets sim_1]',
        'set_property top_lib xil_defaultlib [get_filesets sim_1]',
    ]
    if job.get('defines'):
        d = ' '.join(job['defines'])
        lines += [f'set_property verilog_define {{{d}}} [get_filesets sim_1]',
                  f'set_property verilog_define {{{d}}} [get_filesets sources_1]']
    if job.get('include_dirs'):
        inc = ' '.join(tcl_path(i) for i in job['include_dirs'])
        lines += [f'set_property include_dirs [list {inc}] [get_filesets sim_1]',
                  f'set_property include_dirs [list {inc}] [get_filesets sources_1]']
    if job.get('generics'):
        lines.append('set_property generic {' + ' '.join(job['generics']) + '} [get_filesets sim_1]')
    lines += [
        f'set_property -name {{xsim.simulate.runtime}} -value {{{job.get("tb_time_limit", "25ms")}}} -objects [get_filesets sim_1]',
        'set_property -name {xsim.simulate.log_all_signals} -value {false} -objects [get_filesets sim_1]',
        f'puts "Project ready: {proj_dir}/{job_id}_sim.xpr  top={job["top"]}  expected CHECKS={job.get("checks")}"',
        'puts "Next: Flow Navigator > Run Simulation > Run Behavioral Simulation (or: launch_simulation)"',
    ]
    out = ROOT / 'scripts' / f'vivado_sim_{job_id}.tcl'
    out.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(out)

for j in sys.argv[1:] or ['n2p7_rtt']:
    emit(j)
