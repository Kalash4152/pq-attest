def expected():
    raw = SRC.read_bytes().decode('utf-8')
    nl = '\r\n' if '\r\n' in raw else '\n'
    lines = raw.split(nl)
    for n, old, new in EDITS:
        if lines[n - 1] != old: raise SystemExit(f'prepare_p7ni: line {n} is {lines[n-1]!r}, expected {old!r}')
        lines[n - 1] = new.replace('\n', nl)
    out = HDR.replace('\n', nl) + nl.join(lines)
    left = [i + 1 for i, l in enumerate(out.split(nl)) if 'MAC_FLITS' in l and 'MAC_FLITS_FULL' not in l and not l.lstrip().startswith('//')]
    if left: raise SystemExit(f'prepare_p7ni: MAC_FLITS still used at output lines {left}')
    return out

def main():
    text = expected()
    if '--check' in sys.argv:
        prov = json.loads((D / 'variant_provenance.json').read_text())
        bad = []
        if DST.read_bytes().decode('utf-8') != text: bad.append('noc_network_interface_p7.sv differs from the generator output')
        p = prov.get('noc_network_interface_p7.sv', {})
        if p.get('variant') != sha(DST): bad.append('variant hash mismatch')
        if p.get('base') != sha(SRC): bad.append('base hash mismatch')
        for b in bad: print('FAIL', b)
        if bad: print('P7NI_VARIANT: FAIL'); sys.exit(1)
        print(f'P7NI_VARIANT: PASS (noc_network_interface_p7.sv {sha(DST)[:12]}, base {sha(SRC)[:12]}, {len(EDITS)} edits)')
        return
    DST.write_bytes(text.encode('utf-8'))
    pf = D / 'variant_provenance.json'; prov = json.loads(pf.read_text())
    prov['noc_network_interface_p7.sv'] = dict(base=sha(SRC), base_file='rtl/dual_lane/noc_network_interface.sv', variant=sha(DST),
                                              decision='M-F1 rev 7 R7.1 (per-type MAC framing), R7.4 / C2 (CONTROL_ALLOWED)',
                                              generator='scripts/prepare_p7ni.py')
    pf.write_text(json.dumps(prov, indent=2) + '\n')
    print('wrote', DST.relative_to(ROOT), sha(DST)[:12])

if __name__ == '__main__': main()
