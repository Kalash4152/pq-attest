"""I-6 busy-retry vectors (docs/decisions/I6_CONTRACT.md sec. 4): rows (n_busy, challenges, outcome) from the C-1/C-2
rule in scripts/policy_layer.py, written as vectors/i6_retry.svh for tb_i6_retry. Expected values come from the Python
model, never from the RTL. Default: regenerate in memory and compare with the committed file (job i6_retry_vectors);
--write writes it.
"""
import argparse
import hashlib
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from policy_layer import busy_rows, MAX_BUSY_RETRIES   # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'vectors/i6_retry.svh'


def render():
    rows = busy_rows()
    lines = ['// GENERATED by scripts/gen_i6_vectors.py from scripts/policy_layer.py busy_retry_outcome; do not edit.',
             f'localparam int I6_MAX_BUSY_RETRIES = {MAX_BUSY_RETRIES};',
             f'localparam int I6_ROWS = {len(rows)};',
             '// per row: n_busy BUSY replies, then SUCCESS while challenges are still sent; expected challenges; 1 = GRANT, 0 = FAIL',
             'localparam int I6_N_BUSY [I6_ROWS] = \'{' + ', '.join(str(r[0]) for r in rows) + '};',
             'localparam int I6_CHALLENGES [I6_ROWS] = \'{' + ', '.join(str(r[1]) for r in rows) + '};',
             'localparam int I6_GRANT [I6_ROWS] = \'{' + ', '.join('1' if r[2] == 'GRANT' else '0' for r in rows) + '};']
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--out', help='scheduler evidence directory (unused)')
    a = ap.parse_args()
    text = render()
    if not a.write:
        have = OUT.read_text(encoding='utf-8') if OUT.exists() else ''
        sha = hashlib.sha256(have.encode()).hexdigest()
        if have != text:
            print(f'I6_VECTORS: FAIL {OUT.name} differs from its generation')
            sys.exit(1)
        print(f'I6_VECTORS: PASS rows={len(busy_rows())} sha256={sha}')
        return
    OUT.write_text(text, encoding='utf-8', newline='\n')
    print('wrote', OUT, hashlib.sha256(text.encode()).hexdigest())


if __name__ == '__main__':
    main()
