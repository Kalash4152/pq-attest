"""D-SYN-2 variant check (job dsyn2_variant): protected original unchanged, provenance hashes, TB-only copy equals the
renamed original. Prints DSYN2_VARIANT: PASS or exits non-zero."""
import hashlib, json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
S = ROOT / 'NOC_PQATTEST.srcs/sources_1/new'; D = ROOT / 'rtl/dual_lane'; E = ROOT / 'sim/dual_lane/dsyn2'
sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
def main():
    f = []; o = S / 'pq_measurement.sv'; v = D / 'pq_measurement.sv'
    base = json.loads((ROOT / 'automation/dual_lane_payload/baseline_before.json').read_text())['files']
    prov = json.loads((D / 'variant_provenance.json').read_text()).get('pq_measurement.sv', {})
    if sha(o) != base['NOC_PQATTEST.srcs/sources_1/new/pq_measurement.sv']: f.append('protected original changed')
    if prov.get('base') != sha(o) or prov.get('variant') != sha(v): f.append('provenance mismatch')
    exp = '// GENERATED by scripts/prepare_dsyn2.py from the protected original; TB-only.\n' + \
          o.read_text(encoding='utf-8').replace('module pq_measurement\n', 'module pq_measurement_orig_dsyn2\n')
    if (E / 'pq_measurement_orig_dsyn2.sv').read_text(encoding='utf-8') != exp: f.append('TB-only copy differs from the renamed original')
    for x in f: print('FAIL', x)
    if f: print('DSYN2_VARIANT: FAIL'); sys.exit(1)
    print(f'DSYN2_VARIANT: PASS (base {sha(o)[:12]} variant {sha(v)[:12]})')
if __name__ == '__main__': main()
