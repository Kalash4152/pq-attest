"""S4-A5 (DECISION_REGISTER S4-A5; docs/decisions/S4_AREA_CONTRACT.md). Generates, by exact-anchor edits that must match once,
from pinned sources (hashes in rtl/dual_lane/s4_provenance.json):
  rtl/dual_lane/kmac_128_a5.sv     kmac128 (same name as the production core) without the 1,600-bit state copy (E3, E4)
  rtl/dual_lane/kmac_128_xp_a5.sv  kmac128_xp (S3-A1 permutation port) without the state copy (E1)
The A5 transform is the one written and measured in S3 (commit 3fd54110, withdrawn there because it added LUTs under
-flatten_hierarchy none); S4-F1 flattening turns it into a saving. S3 outputs are not edited.
Usage: python scripts/prepare_s4.py   (writes the variants and the provenance); python scripts/check_s4.py (job s4_variant)"""
import hashlib, json
from pathlib import Path
import prepare_s3 as s3
ROOT = s3.ROOT; S = s3.S; D = s3.D; edit = s3.edit; cut = s3.cut
CONTRACT = 'docs/decisions/S4_AREA_CONTRACT.md'
NL = chr(10)
sha = lambda b: hashlib.sha256(b).hexdigest()

def hdr(src, tag):
    return f'// GENERATED by scripts/prepare_s4.py from {src} ({tag}, {CONTRACT}). Do not edit.' + NL

def kmac_a5(t):
    """S3-A5: the 1,600-bit state_reg copy is no longer read. Absorb base = 0 in BLOCK0, else the core's held state_out;
    the squeeze reads state_out. The three result writes are deleted; the remaining zeroing writes leave state_reg constant
    with no reader, so synthesis removes it."""
    t = edit(t, [
        ('    state_t keccak_state_in;\n    state_t keccak_state_out;\n',
         '    state_t keccak_state_in;\n    state_t keccak_state_out;\n\n'
         "    // S4-A5 (docs/decisions/S4_AREA_CONTRACT.md; first written as S3-A5): absorb from the core's held state_out instead of a\n"
         '    // second 1,600-bit copy. The core holds state_out from done until its next start, and nobody else starts it\n'
         '    // inside a KMAC message; block 0 starts from the zero state.\n'
         '    state_t absorb_base;\n'
         '    always_comb begin\n'
         "        if (ctrl_state == KMAC_BLOCK0) absorb_base = '{default:'0};\n"
         '        else                           absorb_base = keccak_state_out;\n'
         '    end\n'),
        ('        .state_in  (state_reg),\n        .block_in  (absorb_block),', '        .state_in  (absorb_base),\n        .block_in  (absorb_block),'),
        ('state_reg[i/8][0][(i%8)*8 +: 8]', 'keccak_state_out[i/8][0][(i%8)*8 +: 8]')], 'kmac_a5')
    w = '                        state_reg <= keccak_state_out;\n'
    if t.count(w) != 3: raise SystemExit(f'kmac_a5: expected 3 state_reg result writes, found {t.count(w)}')
    t = t.replace(w, '')
    rd = [l for l in (x.split('//')[0] for x in t.split('\n')) if 'state_reg' in l and '<=' not in l and 'state_t state_reg' not in l]
    if rd: raise SystemExit('kmac_a5: state_reg still read: ' + rd[0].strip())
    return t

def kmac_xp_a5(t):
    t = edit(kmac_a5(t), [('module kmac128\n', 'module kmac128_xp\n'),
                 ('    output logic [TAG_BITS-1:0] tag_out,\n    output logic                busy,\n    output logic                done\n);',
                  '    output logic [TAG_BITS-1:0] tag_out,\n    output logic                busy,\n    output logic                done,\n\n' + s3.PORT_DECL)], 'kmac_xp_a5')
    a, b = cut(t, '    keccak_f1600 u_keccak (', 'kmac_xp_a5')
    return (a + "    // S3-A1: the permutation runs in the caller's shared keccak_f1600 (same start / state / done contract).\n"
            '    assign p_start          = keccak_start;\n    assign p_state_in       = keccak_state_in;\n'
            '    assign keccak_state_out = p_state_out;\n    assign keccak_busy      = p_busy;\n    assign keccak_done      = p_done;\n' + b)

PLAN = [(D + 'kmac_128_a5.sv',    S + 'kmac_128.sv', kmac_a5,    'S4-A5'),
        (D + 'kmac_128_xp_a5.sv', S + 'kmac_128.sv', kmac_xp_a5, 'S3-A1 + S4-A5')]

def build():
    out = {}; prov = {}
    for dst, src, fn, tag in PLAN:
        raw = (ROOT / src).read_bytes(); text = raw.decode('utf-8').replace('\r\n', '\n')
        out[dst] = hdr(src, tag) + fn(text)
        prov[dst] = dict(source=src, source_sha256=sha(raw), output_sha256=sha(out[dst].encode('utf-8')))
    return out, prov

def main():
    out, prov = build()
    for dst, text in out.items(): (ROOT / dst).write_bytes(text.encode('utf-8'))
    (ROOT / D / 's4_provenance.json').write_text(json.dumps(dict(schema=1, contract=CONTRACT, files=prov), indent=2) + NL, encoding='utf-8')
    for dst in out: print('wrote', dst)

if __name__ == '__main__': main()
