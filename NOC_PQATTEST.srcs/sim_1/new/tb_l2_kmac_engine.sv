`timescale 1ns/1ps
// Step c (M-F1 rev 7 R7.6/R7.6a; docs/decisions/STEP_C_DESIGN_P7_L2_SHARED.md sec.4): the shared engine
// rtl/dual_lane/l2_kmac_engine.sv alone, four requester stubs (r0, r1 class P; r2, r3 class Q).
// Each stub takes its next vector (22-word transcript and length, payload 0, 7 or 16 words, as GRANT/REVOKE, CHALLENGE,
// RESPONSE) and keeps it stable from its request to its done, honours A1 (requests only while idle, holds req until the grant) and
// draws a new transcript for every job. Phases alternate every 250 grants: random arrivals (1/16 per idle cycle) and
// adversarial (every requester re-requests in the cycle after its own done).
// Reference (contract sec. 5, Q4): real P7 transcripts and tags from scripts/l2_golden.py (ZIP kmac128), both directions
// (r0/r1: 4->3 CHALLENGE/GRANT/REVOKE with K[4->3]; r2/r3: 3->4 RESPONSE with K[3->4]); generated by scripts/gen_l2e_vectors.py,
// checked by job l2e_vectors_check. The expected tag and the owner of each granted job are queued at the grant and
// compared at its done. Provisioning changes mid-job: while a job is in flight both key inputs are driven with garbage
// (restored before the next grant), so only a key latched at the grant gives the expected tag.
// Checks (frozen before the first run), for N_JOBS = 2000:
//   per grant: L2E_P_BOUND (wait <= 269) or L2E_Q_BOUND (wait <= 792)                          2000
//   per done:  L2E_DIGEST (engine tag == reference tag)                                        2000
//   per done:  L2E_JOB_LEN (grant to done, counting the grant cycle, <= J_MAX = 128)            2000
//   per done:  L2E_OWNER (the engine's owner at done is the requester granted for that job: exactly its tag, once) 2000
//   L2E_A1 (no cycle with the owner requesting while its job is in flight), L2E_A2 (at most 4 idle cycles with a
//   request pending between a done and the next grant)                                            2
//   coverage: L2E_COVER_LENS (each payload length >= 100 jobs), L2E_COVER_FORCED_Q (>= 50 Q grants while a P request
//   was pending), L2E_COVER_P_WAIT (max P wait >= J_MIN + 1), L2E_COVER_Q_WAIT (max Q wait >= 3 * J_MIN)       4
//   reset (contract sec. 5): reset asserted for 3 cycles at the grant, at load index 0 / 11 / 21, at the kmac start, in
//   the middle of the kmac run and in the done cycle; then L2E_RST_<P>_NO_STALE (no done, engine idle, for 200 cycles)
//   and L2E_RST_<P>_FRESH_OK (a new job returns its reference tag)                                   7 x 2 = 14
//   CHECKS = 8020. J_MIN = 100 is a lower bound on any job (22 stream cycles + the kmac128 run).
// Bounded: no grant for 20000 cycles, or a reference result missing at the end, is TB_TIMEOUT (INVALID).
module tb_l2_kmac_engine;
  localparam int N_JOBS = 2000, J_MAX = 128, J_MIN = 100, PB = 269, QB = 792;
  localparam logic [111:0] DOMAIN = 112'h31762d485455412d324c2d434f4e;
  logic clk = 0, rst = 1; always #10 clk = ~clk;
  logic [255:0] k43, k34, kk [2]; bit garble = 0, stubs_on = 1;
  assign k43 = garble ? ~kk[0] : kk[0];
  assign k34 = garble ? ~kk[1] : kk[1];
  always @(negedge clk) garble <= busy;   // key inputs change after the grant and are restored before the next one
  logic [839:0] vec [4000]; int vi [4] = '{0, 0, 0, 0};
  logic [3:0] req = '0; logic [3:0][31:0] wd; logic [3:0][6:0] mlen;
  logic grant, busy, done; logic [1:0] grant_id, owner; logic [4:0] widx; logic [127:0] tag;
  l2_kmac_engine #(.OVH(4)) dut (.clk, .rst, .key_43(k43), .key_34(k34), .req, .wd, .mlen, .grant, .grant_id, .busy,
                                 .owner, .widx, .done, .tag);
  logic [31:0] words [4][22]; logic [6:0] len [4]; bit in_job [4]; longint t_req [4];
  always_comb for (int r = 0; r < 4; r++) begin wd[r] = words[r][widx]; mlen[r] = len[r]; end
  logic [31:0] lcg = 32'h6E61_7C01;
  function automatic logic [31:0] rnd(); lcg = lcg * 32'd1664525 + 32'd1013904223; return lcg; endfunction
  int checks = 0, errors = 0, shown = 0;
  task automatic check(input bit ok, input string name);
    checks++; if (!ok) begin errors++; if (shown < 20) begin shown++; $display("[FAIL] %s", name); end end
  endtask
  logic [127:0] etag [4];
  task automatic new_transcript(input int r);
    automatic logic [839:0] v = vec[r * 1000 + vi[r] % 1000];
    for (int k = 0; k < 22; k++) words[r][k] = v[k*32 +: 32];
    len[r] = v[710:704]; etag[r] = v[839:712]; vi[r]++;
  endtask

  logic [127:0] ref_q[$], eng_q[$]; logic [1:0] own_q[$]; int ownn = 0;

  // ---------------- requester stubs, monitors
  longint cyc = 0; int grants = 0, dones = 0, phase = 0, maxp = 0, maxq = 0, forced = 0, a1 = 0, gapmax = 0, gap = 0, jl = 0, cmpn = 0;
  int lens [3] = '{0, 0, 0};
  always @(posedge clk) begin
    cyc++;
    if (!rst && stubs_on) begin
      if (busy && req[owner]) a1++;
      if (grant && gap > gapmax) gapmax = gap;                 // measured before the reset below
      if (done || grant) gap = 0; else if (!busy && req != 0) gap++;
      if (grant) begin
        automatic int w = int'(cyc - t_req[grant_id]) + 1; automatic bit isp = grant_id < 2;
        grants++;
        if (isp) begin if (w > maxp) maxp = w; end else begin if (w > maxq) maxq = w; if (req[0] | req[1]) forced++; end
        if (grants <= N_JOBS) check(w <= (isp ? PB : QB), $sformatf("%s wait=%0d grant=%0d r%0d", isp ? "L2E_P_BOUND" : "L2E_Q_BOUND", w, grants, grant_id));
        ref_q.push_back(etag[grant_id]); own_q.push_back(grant_id);
        lens[len[grant_id] == 24 ? 0 : len[grant_id] == 52 ? 1 : 2]++;
        req[grant_id] <= 1'b0; in_job[grant_id] = 1; jl = 1;
      end else if (busy) jl++;
      if (done) begin
        dones++; eng_q.push_back(tag);
        begin automatic logic [1:0] o;
          o = own_q.size() ? own_q.pop_front() : 2'bxx;
          ownn++; if (ownn <= N_JOBS) check(owner === o, $sformatf("L2E_OWNER job=%0d owner=%0d granted=%0d", ownn, owner, o));
          // release the requester that was granted this job (equal to owner on correct RTL): a misrouted completion is
          // caught by L2E_OWNER / L2E_DIGEST, and the stubs keep running instead of hanging the bench
          if (o !== 2'bxx) in_job[o] = 0;
        end
        if (dones <= N_JOBS) check(jl + 1 <= J_MAX, $sformatf("L2E_JOB_LEN %0d job=%0d r%0d", jl + 1, dones, owner));
      end
      while (eng_q.size() > 0 && ref_q.size() > 0) begin
        automatic logic [127:0] e = eng_q.pop_front(), x = ref_q.pop_front();
        cmpn++; if (cmpn <= N_JOBS) check(e == x, $sformatf("L2E_DIGEST job=%0d eng=%h ref=%h", cmpn, e, x));
      end
      for (int r = 0; r < 4; r++)
        if (!req[r] && !in_job[r] && !(grant && grant_id == r) && !(done && owner == r))
          if (phase == 1 || rnd() % 16 == 0) begin new_transcript(r); req[r] <= 1'b1; t_req[r] = cyc + 1; end
      phase = (grants / 250) % 2;
    end
  end
  // ---------------- reset scenarios (stubs off; requester 0 driven directly)
  // A1 handshake as the stubs do it: req[0] is held until the clock edge that takes its grant (the grant is combinational,
  // so clearing req at a negedge where grant = 1 would withdraw the request before the edge)
  always @(posedge clk) if (!stubs_on && !rst && grant && grant_id == 2'd0) req[0] <= 1'b0;
  task automatic rst_scenarios();
    string pn [7] = '{"GRANT", "LOAD0", "LOAD11", "LOAD21", "RUN_START", "RUN_MID", "DONE"};
    stubs_on = 0; @(negedge clk); req = '0;
    begin automatic int n = 0; while ((busy || dut.es != 0) && n < 2000) begin @(negedge clk); n++; end end
    for (int s = 0; s < 7; s++) begin
      automatic int n = 0, d0, run = 0; automatic bit hit = 0;
      new_transcript(0); req[0] = 1; #1;              // let the combinational grant settle before sampling it
      while (!hit && n < 3000) begin
        case (s)
          0: hit = grant;
          1: hit = dut.es == 1 && dut.wcnt == 0;
          2: hit = dut.es == 1 && dut.wcnt == 11;
          3: hit = dut.es == 1 && dut.wcnt == 21;
          4: hit = dut.es == 3;
          5: begin if (dut.es == 3) run++; hit = run == 40; end
          default: hit = done;
        endcase
        if (!hit) begin @(negedge clk); n++; end
      end
      if (!hit) begin $display("TB_TIMEOUT reset point %s", pn[s]); $finish; end
      rst = 1; req[0] = 0; repeat (3) @(negedge clk); rst = 0;
      d0 = dones;
      begin automatic bit stale = 0;
        repeat (200) begin @(posedge clk); if (done || busy || dut.es != 0) stale = 1; end
        @(negedge clk);
        check(!stale, $sformatf("L2E_RST_%s_NO_STALE", pn[s]));
      end
      new_transcript(0); req[0] = 1; n = 0;
      while (!busy && n < 100) begin @(negedge clk); n++; end   // granted (req[0] cleared at that edge)
      n = 0;
      while (!done && n < 300) begin @(negedge clk); n++; end
      check(done && tag == etag[0], $sformatf("L2E_RST_%s_FRESH_OK done=%b tag=%h ref=%h", pn[s], done, tag, etag[0]));
      @(negedge clk);
    end
  endtask
  initial begin
    int last, n;
`ifdef L2E_LOCAL
    $readmemh("l2e_keys.mem", kk); $readmemh("l2e_vec.mem", vec);
`else
    $readmemh("../../../../../snapshot/sim/dual_lane/l2engine/l2e_keys.mem", kk);
    $readmemh("../../../../../snapshot/sim/dual_lane/l2engine/l2e_vec.mem", vec);
`endif
    if (kk[1] === 'x || vec[3999] === 'x) begin $display("TB_TIMEOUT engine vectors not loaded"); $finish; end
    for (int r = 0; r < 4; r++) begin new_transcript(r); in_job[r] = 0; end
    $display("CONFIG: TOP=tb_l2_kmac_engine N_JOBS=%0d J_MAX=%0d OVH=4 P_BOUND=%0d Q_BOUND=%0d", N_JOBS, J_MAX, PB, QB);
    repeat (4) @(negedge clk); rst = 0;
    last = 0; n = 0;
    while (dones < N_JOBS + 1) begin
      @(negedge clk); n++;
      if (grants != last) begin last = grants; n = 0; end
      if (n > 20000) begin $display("TB_TIMEOUT no grant for 20000 cycles (grants=%0d)", grants); $finish; end
    end
    repeat (10) @(negedge clk);
    if (checks != 4 * N_JOBS) begin $display("TB_TIMEOUT digest compares missing (checks=%0d)", checks); $finish; end
    check(a1 == 0, $sformatf("L2E_A1 owner-request cycles=%0d", a1));
    check(gapmax <= 4, $sformatf("L2E_A2 max idle cycles with a request pending=%0d", gapmax));
    check(lens[0] >= 100 && lens[1] >= 100 && lens[2] >= 100, $sformatf("L2E_COVER_LENS %0d/%0d/%0d", lens[0], lens[1], lens[2]));
    check(forced >= 50, $sformatf("L2E_COVER_FORCED_Q %0d", forced));
    check(maxp >= J_MIN + 1, $sformatf("L2E_COVER_P_WAIT %0d", maxp));
    check(maxq >= 3 * J_MIN, $sformatf("L2E_COVER_Q_WAIT %0d", maxq));
    rst_scenarios();
    $display("STATS grants=%0d dones=%0d maxP=%0d maxQ=%0d forcedQ=%0d gapmax=%0d lens=%0d/%0d/%0d", grants, dones, maxp, maxq, forced, gapmax, lens[0], lens[1], lens[2]);
    $display("CHECKS : %0d", checks);
    $display("ERRORS : %0d", errors);
    $display("RESULT : %s", errors == 0 ? "PASS" : "FAIL");
    $finish;
  end
endmodule
